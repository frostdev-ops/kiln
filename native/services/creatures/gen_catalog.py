"""Generates catalog_data.inc (the creature/NPC catalog kiln-creatures ships) from an offline template survey.

    python3 native/services/creatures/gen_catalog.py <templates_full.jsonl> <creature-templates.json> \
        > native/services/creatures/catalog_data.inc

templates_full.jsonl: one JSON object per line, {"guid": "<template GUID>", "v": <tools/kfc decode of the
keen::ecs::TemplateResource>} (tools/kfc/kfc.py decode <guid> keen::ecs::TemplateResource over every template of
`list --type keen::ecs::TemplateResource`; docs/re/creatures.md 1.1). Only facts are kept (names, GUIDs, numbers).
creature-templates.json (id, name) supplies display names.
"""
import json
import sys

FACTIONS = ["Environment", "HitAll", "Fogger", "Vukah", "Scavenger", "Wildlife", "WildBeast", "Player",
            "AutomatedPlayer", "HitOthers", "Skeleton", "PlayerAlly", "FarmAnimal", "Cyclops", "Drak", "Ancients"]
CLASSES = {"Melee": 0, "Ranger": 1, "Mage": 2}
# kind: 1 enemy AI (enemy01), 2 wildlife, 3 animal (farm/pet), 4 villager / workshop NPC
F_BOSS, F_PHASES, F_SAVED, F_GUARD_PLAYER, F_ALLY, F_WEAKSPOT, F_BOSSBAR = 1, 2, 4, 8, 16, 32, 64


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def guid(v):
    return v if isinstance(v, str) and len(v) == 36 else "00000000-0000-0000-0000-000000000000"


def main():
    names = {}
    with open(sys.argv[2]) as f:
        for g, e in json.load(f).items():
            names[g.lower()] = e.get("name", "")
    rows = []
    with open(sys.argv[1]) as f:
        for line in f:
            r = json.loads(line)
            t = r["v"]
            comps = {c["$type"].split("::")[-1]: c["value"] for c in t["components"]}
            if "Enemy01BehaviorState" in comps:
                kind = 1
            elif "Wildlife" in comps:
                kind = 2
            elif "Animal" in comps:
                kind = 3
            elif "ActiveNpcState" in comps:
                kind = 4
            else:
                continue
            flags = 0
            if "Boss" in comps:
                flags |= F_BOSS
            if "EnemyPhases" in comps:
                flags |= F_PHASES
            if "DoNotSave" not in comps:
                flags |= F_SAVED
            if "BossHealthBar" in comps:
                flags |= F_BOSSBAR
            e01 = comps.get("Enemy01BehaviorState", {})
            if e01.get("guardSetup", {}).get("canGuardPlayer"):
                flags |= F_GUARD_PLAYER
            fac = comps.get("Faction", {}).get("faction", "")
            fi = FACTIONS.index(fac) if fac in FACTIONS else 255
            if fac in ("Player", "PlayerAlly"):
                flags |= F_ALLY
            if t["name"].startswith("Enemy_Weakspot_"):
                flags |= F_WEAKSPOT
            lv = comps.get("Level", {}).get("dataStorage", [0, 0]) or [0, 0]
            loot = comps.get("RandomLoot", {})
            slots = comps.get("RandomLootSlotCount", {})
            row = (
                r["guid"].lower(), t["name"], names.get(r["guid"].lower(), ""), kind, flags, fi,
                int(lv[0]) if len(lv) > 0 else 0, int(lv[1]) if len(lv) > 1 else 0,
                CLASSES.get(e01.get("enemyClass", ""), 255),
                guid(comps.get("EnemyArsenalReference", {}).get("arsenal")),
                guid(loot.get("defaultLabels")), int(slots.get("slotsMin", 0)), int(slots.get("slotsMax", 0)),
                float(comps.get("ExperienceSource", {}).get("xpMod", 0.0)),
                float(comps.get("ScaleComponent", {}).get("uniformScale", 1.0)),
                guid(comps.get("ModelResource", {}).get("model")),
                guid(comps.get("AnimationGraphResourceComponent2", {}).get("animationGraph")),
            )
            rows.append(row)
    rows.sort(key=lambda x: x[1].lower())
    print("// Generated by gen_catalog.py from an offline template survey (tools/kfc) and a display-name list;")
    print("// do not edit by hand. { guid, template name, display name, kind, flags, faction, level, level max, enemy class,")
    print("// arsenal, loot labels, loot slots min, max, xp mod, scale, model (client data), animation graph }")
    for r in rows:
        print("{%s, %s, %s, %d, 0x%02x, %d, %d, %d, %d, %s, %s, %d, %d, %sf, %sf, %s, %s}," % (
            c_str(r[0]), c_str(r[1]), c_str(r[2]), r[3], r[4], r[5], r[6], r[7], r[8], c_str(r[9]), c_str(r[10]),
            r[11], r[12], repr(float(r[13])), repr(float(r[14])), c_str(r[15]), c_str(r[16])))
    print("// %d entries" % len(rows), file=sys.stderr)


if __name__ == "__main__":
    main()

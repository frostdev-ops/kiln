"""Generates catalog_data.inc (the template catalog kiln-spawn ships) from a creature catalog (creature-templates.json).

    python3 native/services/spawn/gen_catalog.py <creature-templates.json> \
        > native/services/spawn/catalog_data.inc

Input: {"<template GUID text>": {"template": "<template name>", "name": "<display name>"}, ...}. GUID text is the
standard Windows form (first three groups little-endian in memory), as the game's EML files write it.
Entries Kiln adds itself (EXTRA) are templates seen in the engine code (docs/re/spawn.md).
"""
import json
import sys
import uuid

EXTRA = {
    # spawnPickupItem (RVA 0x166760 on svn 1285601) spawns this template; bytes at RVA 0xbe50f0.
    "a56d2777-daf1-4164-90d4-b7b12749c723": {"template": "Base_LootPickup_Generic_Gravity", "name": "Item pickup"},
}

KINDS = {"creature": 1, "pickup": 2, "prop": 3, "npc": 4, "other": 5}


def kind_of(name):
    n = name.lower()
    if "lootpickup" in n or n.startswith("pickup"):
        return "pickup"
    if "townsfolk" in n or n.startswith("npc_") or "villager" in n:
        return "npc"
    if n.startswith(("enemy_", "base_enemy", "animal_", "base_animal", "fakeplayer_", "player_companion", "boss_",
                     "midboss_", "enemy")):
        return "creature"
    if n.startswith(("prop_", "base_prop", "deco_")):
        return "prop"
    return "other"


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    data = json.load(open(sys.argv[1], encoding="utf-8"))
    data.update(EXTRA)
    rows = []
    for text, v in data.items():
        g = uuid.UUID(text)  # validates
        name = v.get("template") or ""
        rows.append((name, str(g), v.get("name") or "", KINDS[kind_of(name)]))
    rows.sort(key=lambda r: (r[0].lower(), r[1]))
    print("// Generated by gen_catalog.py from a creature catalog; do not edit by hand.")
    print("// { guid text (Windows layout), template name, display name, KILN_TEMPLATE_* kind }")
    for name, g, disp, kind in rows:
        print(f"{{{c_str(g)}, {c_str(name)}, {c_str(disp)}, {kind}}},")


if __name__ == "__main__":
    main()

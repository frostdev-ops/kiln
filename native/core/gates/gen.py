# gen.py <gates dir> <out header> | gen.py --list <gates dir>
# Reads every *.json of the client gate's list (README.md beside this file), checks it, and writes kiln_gates.g.h for
# the core (native/core/src/gates.cpp). --list prints "name<TAB>side<TAB>checks" lines for tools (the guided pass's
# switch list, the docs). A bad file stops the build: a gate that silently did not hold is the one failure this
# list must not have.
import glob, json, os, re, sys

NAME = re.compile(r'^[A-Za-z0-9._/-]{1,96}$')    # kiln.caps names (kiln_caps.h)
CHECK = re.compile(r'^[0-9a-z][0-9a-z._-]*$')    # guided check ids are lower-case
SIDES = {None: 0, 'server': 1, 'client': 2}      # gates.h: kBoth, kServer, kClient


def load(folder):
    gates, seen = [], {}
    for path in sorted(glob.glob(os.path.join(folder, '*.json'))):
        base = os.path.basename(path)
        try:
            doc = json.load(open(path, encoding='utf-8'))
        except ValueError as e:
            sys.exit(f'gates: {base}: not JSON ({e})')
        rows = doc.get('gates') if isinstance(doc, dict) else None
        if not isinstance(rows, list):
            sys.exit(f'gates: {base}: expected {{"gates": [...]}}')
        for i, g in enumerate(rows):
            where = f'{base} entry {i + 1}'
            if not isinstance(g, dict) or set(g) - {'name', 'checks', 'side', 'note'}:
                sys.exit(f'gates: {where}: an object with name, checks and optionally side, note')
            name, checks, side = g.get('name'), g.get('checks'), g.get('side')
            if not isinstance(name, str) or not NAME.match(name):
                sys.exit(f'gates: {where}: name {name!r} is not a capability name')
            if not isinstance(checks, list) or not checks or not all(isinstance(c, str) and CHECK.match(c) for c in checks):
                sys.exit(f'gates: {where} ({name}): checks must be a non-empty list of lower-case check ids')
            if len(set(checks)) != len(checks):
                sys.exit(f'gates: {where} ({name}): a check id is listed twice')
            if side not in SIDES:
                sys.exit(f'gates: {where} ({name}): side must be "server" or "client" when given')
            if name in seen:
                sys.exit(f'gates: {where}: {name} is already held by {seen[name]}')
            seen[name] = base
            gates.append((name, side, checks))
    return sorted(gates)


def main(argv):
    if len(argv) == 3 and argv[1] == '--list':
        for name, side, checks in load(argv[2]):
            print(f'{name}\t{side or "both"}\t{", ".join(checks)}')
        return 0
    if len(argv) != 3:
        sys.exit(__doc__ or 'usage: gen.py <gates dir> <out header> | gen.py --list <gates dir>')
    gates = load(argv[1])
    lines = ['// Generated by native/core/gates/gen.py from native/core/gates/*.json. Do not edit.',
             '// Included by native/core/src/gates.cpp only, after gates.h.',
             'namespace kiln::gates {',
             'inline constexpr Gate kBuiltIn[] = {']
    for name, side, checks in gates:
        lines.append(f'    {{"{name}", "{", ".join(checks)}", {SIDES[side]}}},')
    lines += ['    {nullptr, nullptr, 0},  // the end', '};', '}  // namespace kiln::gates', '']
    text = '\n'.join(lines)
    out = argv[2]
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, 'w', encoding='utf-8') as f:
        f.write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))

/// Durably, through an exclusively created temporary file of a random name ([`crate::durable::json`]); the file goes when
/// nothing is placed and nothing is pending.
fn save_receipts(game: &Path, r: &Receipts) -> Result<()> {
    let file = receipts_path(game);
    crate::engine_mods::refuse_symlink_path(game, &file)?;
    if r.mods.is_empty() && r.ual.is_none() && r.pending.is_empty() && r.cleanup.is_empty() {
        return match std::fs::remove_file(&file) {
            Err(e) if e.kind() != std::io::ErrorKind::NotFound => Err(io_at(&file, "removing")(e)),
            _ => Ok(()),
        };
    }
    crate::durable::json(&file, &Receipts { format: 1, ..r.clone() }, &[])
}

/// One launcher at a time changes these files (another one waits).
fn lock(game: &Path) -> Result<std::fs::File> {
    let path = LOCK.split('/').fold(game.to_path_buf(), |p, c| p.join(c));
    crate::engine_mods::refuse_symlink_path(game, &path)?;
    let dir = path.parent().expect("lock folder");
    std::fs::create_dir_all(dir).map_err(io_at(dir, "creating"))?;
    let f = std::fs::OpenOptions::new().create(true).truncate(false).read(true).write(true).open(&path).map_err(io_at(&path, "opening"))?;
    f.lock().map_err(io_at(&path, "locking"))?;
    Ok(f)
}

/// sha256 of a regular file; None when there is none.
fn sha_of(path: &Path) -> Result<Option<String>> {
    match std::fs::symlink_metadata(path) {
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(io_at(path, "inspecting")(e)),
        Ok(m) if m.is_file() => Ok(Some(crate::hash::sha256_file(path)?.0)),
        Ok(_) => Err(Error::new(ErrorCode::Refused, format!("{}: not a regular file", path.display()))),
    }
}

/// `rel` below `game` with each component as the game folder already spells it (case ignored), so a package's
/// `Scripts/` lands in a `scripts/` that is there, as Windows would have it; the rest as `rel` spells it.
fn spelled(game: &Path, rel: &str) -> Result<String> {
    CasePaths::new(game).spelled(rel)
}

/// A read-only pass lists each folder once, including exact matches: Linux can have two spellings at once.
struct CasePaths<'a> {
    game: &'a Path,
    dirs: BTreeMap<PathBuf, BTreeMap<String, Vec<String>>>,
}

impl<'a> CasePaths<'a> {
    fn new(game: &'a Path) -> Self { Self { game, dirs: BTreeMap::new() } }

    fn spelled(&mut self, rel: &str) -> Result<String> {
        let mut at = self.game.to_path_buf();
        let mut out = Vec::new();
        for part in rel.split('/').filter(|p| !p.is_empty()) {
            if !self.dirs.contains_key(&at) {
                let mut names: BTreeMap<String, Vec<String>> = BTreeMap::new();
                match std::fs::read_dir(&at) {
                    Ok(entries) => for entry in entries {
                        let name = entry.map_err(io_at(&at, "reading"))?.file_name();
                        if let Some(name) = name.to_str() {
                            names.entry(name.to_ascii_lowercase()).or_default().push(name.to_string());
                        }
                    },
                    Err(e) if e.kind() == std::io::ErrorKind::NotFound => {},
                    Err(e) => return Err(io_at(&at, "reading")(e)),
                }
                self.dirs.insert(at.clone(), names);
            }
            let matches = self.dirs[&at].get(&part.to_ascii_lowercase());
            if matches.is_some_and(|names| names.len() > 1) {
                return Err(Error::new(ErrorCode::Refused, format!(
                    "{}: more than one name matches {part} ignoring case; keep just one spelling before activating or removing mods", at.display())));
            }
            let name = matches.and_then(|names| names.first()).cloned().unwrap_or_else(|| part.to_string());
            at.push(&name);
            out.push(name);
        }
        Ok(out.join("/"))
    }
}

fn host(game: &Path, rel: &str) -> PathBuf {
    rel.split('/').fold(game.to_path_buf(), |p, c| p.join(c))
}

/// Removes the folders between `path` and the game folder that are empty now (the ones Kiln made for a package).
fn remove_empty_parents(game: &Path, path: &Path) {
    for d in path.ancestors().skip(1) {
        if d == game || !d.starts_with(game) || std::fs::remove_dir(d).is_err() { break; }
    }
}

// ---- file changes that never write over a file that is not Kiln's ----

/// `.<name>.<tag>.kiln-<what>` next to `path`: a file staged for it (`new`) or the file moved aside from it (`old`).
fn side_file(path: &Path, tag: &str, what: &str) -> PathBuf {
    let name = path.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
    path.with_file_name(format!(".{name}.{tag}.kiln-{what}"))
}

/// Finds a journal side file even when its parent or destination was renamed only by case.
fn side_at(paths: &mut CasePaths<'_>, rel: &str, tag: &str, what: &str) -> Result<PathBuf> {
    let path = side_file(Path::new(rel), tag, what);
    let rel = paths.spelled(&path.to_string_lossy().replace('\\', "/"))?;
    Ok(host(paths.game, &rel))
}

/// Writes `bytes` into a new file next to `path` (created exclusively, flushed).
fn stage(path: &Path, tag: &str, bytes: &[u8]) -> Result<PathBuf> {
    use std::io::Write;
    let staged = side_file(path, tag, "new");
    let dir = path.parent().ok_or_else(|| Error::invalid(format!("{}: no parent folder", path.display())))?;
    crate::durable::ensure_dir(dir)?;
    let mut f = std::fs::OpenOptions::new().write(true).create_new(true).open(&staged).map_err(io_at(&staged, "writing"))?;
    let written = f.write_all(bytes).and_then(|_| f.sync_all()).map_err(io_at(&staged, "writing"));
    drop(f);
    written.inspect_err(|_| { let _ = std::fs::remove_file(&staged); })?;
    // Keep the file's identity until its receipt commits. Equal bytes alone cannot prove that we published it.
    let proof = side_file(path, tag, "owned");
    ownership_link(&staged, &proof).map_err(|e| Error::new(ErrorCode::Refused, format!(
        "{}: cannot record file ownership ({e}); game-folder mods need a drive that supports hard links and allows writing", proof.display())))
        .inspect_err(|_| { let _ = std::fs::remove_file(&staged); })?;
    crate::durable::flush_dir(dir)?;
    Ok(staged)
}

fn ownership_link(from: &Path, to: &Path) -> std::io::Result<()> {
    #[cfg(test)]
    if FAIL_OWNERSHIP_LINK.with(|s| s.get()) { return Err(std::io::ErrorKind::Unsupported.into()); }
    std::fs::hard_link(from, to)
}

/// Both names still refer to the same physical file, rather than two files with equal content.
fn same_file(a: &Path, b: &Path) -> Result<bool> {
    let identity = |path: &Path| -> Result<(u64, u64)> {
        #[cfg(unix)]
        {
            use std::os::unix::fs::MetadataExt;
            let m = std::fs::metadata(path).map_err(io_at(path, "inspecting file identity"))?;
            Ok((m.dev(), m.ino()))
        }
        #[cfg(windows)]
        {
            use std::os::windows::io::AsRawHandle;
            use windows_sys::Win32::Storage::FileSystem::{BY_HANDLE_FILE_INFORMATION, GetFileInformationByHandle};
            let f = std::fs::File::open(path).map_err(io_at(path, "opening"))?;
            let mut info = std::mem::MaybeUninit::<BY_HANDLE_FILE_INFORMATION>::uninit();
            // SAFETY: the handle is open and info points to a writable struct of the required size.
            if unsafe { GetFileInformationByHandle(f.as_raw_handle(), info.as_mut_ptr()) } == 0 {
                return Err(io_at(path, "inspecting file identity")(std::io::Error::last_os_error()));
            }
            // SAFETY: the successful call initialized info.
            let info = unsafe { info.assume_init() };
            Ok((u64::from(info.dwVolumeSerialNumber), u64::from(info.nFileIndexHigh) << 32 | u64::from(info.nFileIndexLow)))
        }
        #[cfg(not(any(unix, windows)))]
        Err(Error::new(ErrorCode::Unsupported, format!("{}: file identity is unavailable", path.display())))
    };
    Ok(identity(a)? == identity(b)?)
}

fn remove_proof(paths: &mut CasePaths<'_>, rel: &str, tag: &str) -> Result<()> {
    crate::bundle::safe_rel_path(rel)?;
    for what in ["new", "owned"] {
        let proof = side_at(paths, rel, tag, what)?;
        crate::engine_mods::refuse_symlink_path(paths.game, &proof)?;
        match std::fs::remove_file(&proof) {
            Err(e) if e.kind() != std::io::ErrorKind::NotFound => return Err(io_at(&proof, "removing")(e)),
            _ => {},
        }
        if let Some(dir) = proof.parent().filter(|p| p.is_dir()) { crate::durable::flush_dir(dir)?; }
    }
    Ok(())
}

fn finish_cleanup(game: &Path, rc: &mut Receipts) -> Result<()> {
    if rc.cleanup.is_empty() { return Ok(()); }
    #[cfg(test)]
    if STOP_BEFORE_CLEANUP.with(|s| s.get()) { return Err(Error::invalid("injected stop after commit")); }
    let mut paths = CasePaths::new(game);
    for side in &rc.cleanup { remove_proof(&mut paths, &side.rel, &side.tag)?; }
    rc.cleanup.clear();
    save_receipts(game, rc)
}

/// Moves `from` to `to` only while there is no file at `to`: false (and `from` stays) when one is there.
#[cfg(not(windows))]
fn publish_new(from: &Path, to: &Path) -> Result<bool> {
    // a hard link is created only where no name is: the no-replace rename Unix has in every file system std reaches
    match std::fs::hard_link(from, to) {
        Ok(()) => std::fs::remove_file(from).map_err(io_at(from, "removing"))?,
        Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => return Ok(false),
        // Fail closed when the filesystem cannot publish without replacing a name.
        Err(e) => return Err(io_at(to, "publishing without replacement")(e)),
    }
    if let Some(dir) = to.parent() { crate::durable::flush_dir(dir)?; }
    Ok(true)
}

/// Moves `from` to `to` only while there is no file at `to` (`MoveFileExW` without `MOVEFILE_REPLACE_EXISTING`).
#[cfg(windows)]
fn publish_new(from: &Path, to: &Path) -> Result<bool> {
    use windows_sys::Win32::Storage::FileSystem::{MoveFileExW, MOVEFILE_WRITE_THROUGH};
    let (src, dst) = (crate::util::win32_path(from)?, crate::util::win32_path(to)?);
    // SAFETY: both are NUL-terminated UTF-16 strings that live until the call returns.
    if unsafe { MoveFileExW(src.as_ptr(), dst.as_ptr(), MOVEFILE_WRITE_THROUGH) } == 0 {
        let e = std::io::Error::last_os_error();
        if e.kind() == std::io::ErrorKind::AlreadyExists { return Ok(false); }
        return Err(io_at(to, "renaming to")(e));
    }
    Ok(true)
}

/// How one file change went.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Outcome {
    Done,
    /// The file there no longer held Kiln's bytes: left as it is.
    Changed,
    /// A file appeared where Kiln was to write a new one: left as it is, Kiln's not written.
    Taken,
}

/// A new file where there is none: never over a file that appeared meanwhile.
fn put_new(game: &Path, rel: &str, bytes: &[u8], tag: &str) -> Result<Outcome> {
    let dst = host(game, rel);
    crate::engine_mods::refuse_symlink_path(game, &dst)?;
    let staged = stage(&dst, tag, bytes)?;
    match publish_new(&staged, &dst) {
        Ok(true) => Ok(Outcome::Done),
        other => {
            let _ = std::fs::remove_file(&staged);
            other.map(|_| Outcome::Taken)
        }
    }
}

/// Replaces (`new`) or removes (None) the file at `rel` while it holds Kiln's bytes `expected`: the file is moved aside
/// first and checked there, so a file someone changed in the meantime is never written over or deleted; it goes back.
fn swap(game: &Path, rel: &str, expected: &str, new: Option<&[u8]>, tag: &str) -> Result<Outcome> {
    let dst = host(game, rel);
    crate::engine_mods::refuse_symlink_path(game, &dst)?;
    let parked = side_file(&dst, tag, "old");
    if std::fs::symlink_metadata(&parked).is_ok() {
        return Err(Error::new(ErrorCode::Refused, format!("{}: in the way of Kiln's change of {}", parked.display(), dst.display())));
    }
    match std::fs::rename(&dst, &parked) {
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return match new {
            Some(b) => put_new(game, rel, b, tag),
            None => Ok(Outcome::Done),
        },
        Err(e) => return Err(io_at(&dst, "moving aside")(e)),
        Ok(()) => {}
    }
    if sha_of(&parked)?.as_deref() != Some(expected) {
        if !publish_new(&parked, &dst)? {
            return Err(Error::new(ErrorCode::Refused, format!("{}: changed while Kiln placed files, and another file appeared there; \
                the earlier one is at {}", dst.display(), parked.display())));
        }
        return Ok(Outcome::Changed);
    }
    let outcome = match new {
        None => Outcome::Done,
        Some(b) => {
            let staged = stage(&dst, tag, b)?;
            if publish_new(&staged, &dst)? { Outcome::Done } else {
                let _ = std::fs::remove_file(&staged);
                Outcome::Taken
            }
        }
    };
    std::fs::remove_file(&parked).map_err(io_at(&parked, "removing"))?;
    if new.is_none() { remove_empty_parents(game, &dst); }
    if let Some(dir) = dst.parent().filter(|d| d.is_dir()) { crate::durable::flush_dir(dir)?; }
    Ok(outcome)
}

// ---- the report ----

/// What [`place`] did.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct GameFilesReport {
    /// `native:<id>` whose files Kiln wrote (new, or another version).
    pub placed: Vec<String>,
    /// `native:<id>` already in place.
    pub kept: Vec<String>,
    /// `native:<id>` whose files Kiln removed (off, gone from the profile).
    pub removed: Vec<String>,
    /// One sentence each: what Kiln placed or removed, and what it could not do and why (`native:<id>: ...`).
    pub notes: Vec<String>,
    /// Code files Kiln placed that changed since and therefore stay where they are: they may still run.
    pub retained: Vec<RetainedPlacement>,
}

fn tag(id: &str) -> String {
    format!("native:{id}")
}

fn names(files: &[String]) -> String {
    let mut v: Vec<&str> = files.iter().map(String::as_str).take(4).collect();
    if files.len() > 4 { v.push("..."); }
    v.join(", ")
}

fn new_tag() -> Result<String> {
    Ok(crate::hash::hex(&crate::util::random_bytes::<8>()?))
}

// ---- recovery ----

/// Settles what a stop left between an intent and its commit, from what is on disk: a file moved aside goes back where
/// it was when nothing is there now, a staged file goes, and a new file is Kiln's only when its identity link proves
/// publication. Earlier owned bytes still count too. Then the intent ends. Nothing is written over.
fn recover(game: &Path, rc: &mut Receipts, rep: &mut GameFilesReport) -> Result<()> {
    if rc.pending.is_empty() { return finish_cleanup(game, rc); }
    let mut paths = CasePaths::new(game);
    for intent in std::mem::take(&mut rc.pending) {
        let mut files: Vec<(String, Option<String>)> = Vec::new();
        for op in &intent.ops {
            crate::bundle::safe_rel_path(&op.rel)?;
            let rel = paths.spelled(&op.rel)?;
            let dst = host(game, &rel);
            crate::engine_mods::refuse_symlink_path(game, &dst)?;
            let staged = side_at(&mut paths, &op.rel, &intent.tag, "new")?;
            if std::fs::symlink_metadata(&staged).is_ok_and(|m| m.is_file()) {
                std::fs::remove_file(&staged).map_err(io_at(&staged, "removing"))?;
            }
            let parked = side_at(&mut paths, &op.rel, &intent.tag, "old")?;
            if std::fs::symlink_metadata(&parked).is_ok_and(|m| m.is_file()) {
                if std::fs::symlink_metadata(&dst).is_err() {
                    publish_new(&parked, &dst)?;
                } else if op.before.is_some() && sha_of(&parked)? == op.before {
                    std::fs::remove_file(&parked).map_err(io_at(&parked, "removing"))?;
                } else {
                    rep.notes.push(format!("{}: an interrupted change left a file at {}; Kiln leaves it there", dst.display(), parked.display()));
                }
            }
            let have = sha_of(&dst)?;
            let proof = side_at(&mut paths, &op.rel, &intent.tag, "owned")?;
            crate::engine_mods::refuse_symlink_path(game, &proof)?;
            let published = have.is_some() && have == op.after && proof.is_file() && same_file(&dst, &proof)?;
            let kilns = have.is_some() && (have == op.before || published);
            files.push((rel, if kilns { have } else { None }));
            rc.cleanup.push(Cleanup { rel: op.rel.clone(), tag: intent.tag.clone() });
        }
        match &intent.owner {
            Owner::Ual { from } => {
                rc.ual = files.into_iter().find_map(|(_, s)| s).map(|sha256| PlacedUal { from: from.clone(), sha256 });
            }
            Owner::Mod { id, version, hash, shape, loader } => {
                let at = rc.mods.iter().position(|p| p.id == *id);
                let mut entry = at.map(|i| rc.mods.remove(i)).unwrap_or_else(|| Placed { id: id.clone(), version: version.clone(),
                    hash: hash.clone(), shape: *shape, loader: loader.clone(), files: BTreeMap::new() });
                for (rel, sha) in files {
                    entry.files.retain(|r, _| !r.eq_ignore_ascii_case(&rel));
                    if let Some(sha) = sha { entry.files.insert(rel, sha); }
                }
                rc.mods.push(entry);
            }
        }
        rep.notes.push(format!("{}: a change Kiln began earlier was interrupted; Kiln settled it from the files in the game folder",
            match &intent.owner { Owner::Mod { id, .. } => tag(id), Owner::Ual { .. } => format!("Ultimate ASI Loader ({UAL_FILE})") }));
    }
    save_receipts(game, rc)?;
    finish_cleanup(game, rc)
}

// ---- working out what changes ----

/// One package's changes, or Ultimate ASI Loader's ([`preflight`]): its intent, the bytes it writes, and the receipt
/// lines that stay as they are.
struct Job {
    intent: Intent,
    bytes: BTreeMap<String, Vec<u8>>,
    /// Kiln's files of it that need no change (game-relative -> sha256).
    keep: BTreeMap<String, String>,
    /// What to say once it is done (when it changed something).
    done: Option<String>,
    /// Gone from the profile: `removed` in the report.
    removal: bool,
}

/// Everything an activation would change, worked out before anything is written.
struct Preflight {
    jobs: Vec<Job>,
    notes: Vec<String>,
    retained: Vec<RetainedPlacement>,
    /// Receipt lines of files that are not Kiln's any more (changed settings): dropped at the commit.
    released: Vec<(String, String)>,
    /// The packages placed as they are (`kept` in the report).
    kept: Vec<String>,
    /// Ultimate ASI Loader's receipt goes (a changed UAL that is not Kiln's any more).
    drop_ual: bool,
}

/// What a package of the profile needs: its Library folder and plan.
type Wanted<'a> = (&'a ProfileMod, PathBuf, GamePlan);

fn wanted_of<'a>(dirs: &DataDirs, mods: &'a [ProfileMod]) -> Vec<Wanted<'a>> {
    mods.iter().filter(|m| m.enabled).filter_map(|m| {
        let r = LibraryRef { kind: ModKind::Native, id: m.id.clone(), version: m.version.clone(), hash: m.hash.clone() };
        let folder = crate::library::path_of(dirs, &r).ok()?;
        let plan = plan(&folder)?;
        Some((m, folder, plan))
    }).collect()
}

/// Removal ops for Kiln's files of an earlier placement (`files`, game-relative -> sha256) that the new plan does not
/// place again (`keep_rels`): a file still Kiln's goes, a changed code file stays (retained, its receipt line kept), a
/// changed settings file is the player's from now on.
fn removals(paths: &mut CasePaths<'_>, id: &str, files: &BTreeMap<String, String>, keep_rels: &[String], off: bool, pf: &mut Preflight,
            ops: &mut Vec<Op>, keep: &mut BTreeMap<String, String>) -> Result<()> {
    let game = paths.game;
    let mut settings = Vec::new();
    for (rel, sha) in files {
        if keep_rels.iter().any(|k| k.eq_ignore_ascii_case(rel)) { continue; }
        crate::bundle::safe_rel_path(rel)?;
        let actual = paths.spelled(rel)?;
        let path = host(game, &actual);
        crate::engine_mods::refuse_symlink_path(game, &path)?;
        match sha_of(&path)? {
            None => {}
            Some(have) if have == *sha => ops.push(Op { rel: actual.clone(), before: Some(have), after: None }),
            Some(_) if is_code(rel) => {
                keep.insert(actual, sha.clone());
                pf.retained.push(RetainedPlacement { path, may_run: true, off, reason: format!(
                    "{}: changed since Kiln placed it in the game folder; Kiln neither replaces nor removes it", tag(id)) });
            }
            Some(_) => {
                settings.push(rel.clone());
                pf.released.push((id.to_string(), rel.clone()));
            }
        }
    }
    if !settings.is_empty() {
        pf.notes.push(format!("{}: {} changed since Kiln placed it and stay in the game folder (your settings): {}", tag(id),
            if settings.len() == 1 { "this file" } else { "these files" }, names(&settings)));
    }
    Ok(())
}

/// Where Ultimate ASI Loader comes from for this activation.
enum Ual {
    /// A UAL Kiln did not place is at [`UAL_FILE`] (Kiln's installer chained it, or the player put it there).
    There,
    /// Kiln's copy (current, or written by the job).
    Kilns,
    /// None, with the reason.
    Missing(String),
}

/// Works out every change for the packages of `mods` against the receipts `rc`, reading only: the packages Kiln's
/// receipts hold that the profile does not want go; Ultimate ASI Loader; each package the profile wants, whole or not at
/// all (a code file in the way keeps all of it out, the files of its earlier version included).
fn preflight(dirs: &DataDirs, mods: &[ProfileMod], game: &Path, rc: &Receipts) -> Result<Preflight> {
    let mut paths = CasePaths::new(game);
    let mut pf = Preflight { jobs: Vec::new(), notes: Vec::new(), retained: Vec::new(), released: Vec::new(), kept: Vec::new(), drop_ual: false };
    let wanted = wanted_of(dirs, mods);
    let (mapped, _) = one_place_each(wanted.iter().flat_map(|(_, _, p)| p.files.iter().map(|(_, r)| (r.clone(), r.clone()))).collect());
    let mapped: BTreeMap<String, String> = mapped.into_iter().collect();
    let mut reserved: BTreeMap<String, String> = BTreeMap::new();

    // Ultimate ASI Loader for the .asi packages
    let need_ual = wanted.iter().any(|(_, _, p)| p.shape == Shape::Asi && p.problem.is_none());
    let ual_rel = paths.spelled(UAL_FILE)?;
    let ual_path = host(game, &ual_rel);
    crate::engine_mods::refuse_symlink_path(game, &ual_path)?;
    let at_slot = sha_of(&ual_path)?;
    let ours = rc.ual.as_ref().is_some_and(|u| at_slot.as_deref() == Some(u.sha256.as_str()));
    let brought = wanted.iter().filter(|(_, _, p)| p.problem.is_none())
        .find_map(|(m, folder, p)| p.ual.as_ref().map(|u| (m.id.clone(), folder.join(u))));
    let ual_job = |from: &str, after: Option<(String, Vec<u8>)>| -> Result<Job> {
        let mut bytes = BTreeMap::new();
        let op = Op { rel: ual_rel.clone(), before: at_slot.clone().filter(|_| ours), after: after.as_ref().map(|(s, _)| s.clone()) };
        if let Some((_, b)) = after { bytes.insert(ual_rel.clone(), b); }
        Ok(Job { intent: Intent { tag: new_tag()?, owner: Owner::Ual { from: from.to_string() }, ops: vec![op] }, bytes,
            keep: BTreeMap::new(), done: None, removal: false })
    };
    let ual = if !need_ual {
        Ual::Missing(String::new())
    } else {
        match (&at_slot, ours, &brought) {
            (Some(_), false, _) if is_ual_at(&ual_path) => Ual::There,
            (Some(_), false, _) => Ual::Missing(format!("{UAL_FILE} next to the game is not Ultimate ASI Loader and Kiln did not place it \
                ({}); Kiln leaves it as it is", crate::pe::classify_proxy(&ual_path).ok().and_then(|c| c.detail).unwrap_or_else(|| "another DLL".into()))),
            (_, _, Some((from, src))) => {
                let b = std::fs::read(src).map_err(io_at(src, "reading"))?;
                let sha = crate::hash::sha256_hex(&b);
                if at_slot.as_deref() != Some(sha.as_str()) || rc.ual.as_ref().is_some_and(|u| u.from != *from) {
                    let mut job = ual_job(from, Some((sha, b)))?;
                    job.done = Some(format!("{}: Kiln placed its Ultimate ASI Loader next to the game as {UAL_FILE} (Kiln's own \
                        dinput8.dll stays); Kiln's proxy loads it from kiln/chain.ini, and Kiln removes it again when no mod of the \
                        profile needs it. Under Proton it needs the Steam launch option {}", tag(from), crate::game::CHAINED_DLL_OVERRIDE_ADVICE));
                    pf.jobs.push(job);
                }
                Ual::Kilns
            }
            (Some(_), true, None) => Ual::Missing("no package of this profile that is on brings Ultimate ASI Loader any more".into()),
            (None, _, None) => Ual::Missing(String::new()),
        }
    };
    // Kiln's UAL that no package of the profile needs or brings now goes (when it is unchanged)
    if !matches!(ual, Ual::Kilns) && let Some(u) = &rc.ual {
        if ours {
            pf.jobs.push(ual_job(&u.from, None)?);
        } else {
            if at_slot.is_some() {
                pf.retained.push(RetainedPlacement { path: ual_path.clone(), may_run: true, off: true, reason: format!(
                    "Ultimate ASI Loader ({UAL_FILE}) changed since Kiln placed it for {}; Kiln neither replaces nor removes it", tag(&u.from)) });
            }
            pf.drop_ual = true;
        }
    }
    let ual_ok = matches!(ual, Ual::There | Ual::Kilns);
    for (m, _, p) in wanted.iter().filter(|(_, _, p)| p.shape == Shape::Asi && p.problem.is_none() && !ual_ok) {
        let why = match &ual { Ual::Missing(w) if !w.is_empty() => format!(" ({w})"), _ => String::new() };
        pf.notes.push(format!("{}: its .asi plugins need Ultimate ASI Loader, which is not in this game{why}: add Ultimate ASI Loader's \
            download (its dinput8.dll) to the Library and switch it on in this profile, then activate the profile again. \
            Kiln placed none of its {} file(s)", tag(&m.id), p.files.len()));
    }

    // each package the profile wants, worked out whole before anything of it (or of its earlier version) changes
    let mut held: Vec<String> = Vec::new();
    for (m, folder, p) in wanted.iter().filter(|(_, _, p)| p.shape == Shape::Loader || ual_ok || p.problem.is_some()) {
        let t = tag(&m.id);
        let prev = rc.mods.iter().find(|x| x.id == m.id);
        let had = prev.is_some_and(|x| x.version == m.version && x.hash == m.hash);
        if let Some(problem) = &p.problem {
            pf.notes.push(format!("{t}: not placed in the game folder: {problem}"));
            held.push(m.id.clone());
            continue;
        }
        let owned_now = |rel: &str, have: &str| prev.is_some_and(|x| x.files.iter().any(|(r, s)| r.eq_ignore_ascii_case(rel) && s == have));
        let (mut ops, mut bytes, mut keep) = (Vec::new(), BTreeMap::new(), BTreeMap::new());
        let (mut blocked, mut theirs, mut same) = (None, Vec::new(), Vec::new());
        let mut targets = Vec::new();
        for (src, rel) in &p.files {
            let rel = paths.spelled(&mapped[rel])?;
            if let Some(other) = reserved.get(&rel.to_ascii_lowercase()) {
                blocked = Some(format!("{rel} is also needed by {other}"));
                break;
            }
            if let Some(other) = rc.mods.iter().find(|x| x.id != m.id && wanted.iter().any(|(m, _, _)| m.id == x.id)
                && (x.files.keys().any(|r| r.eq_ignore_ascii_case(&rel)) || x.loader.as_ref().is_some_and(|r| r.eq_ignore_ascii_case(&rel)))) {
                blocked = Some(format!("{rel} still belongs to {}", tag(&other.id)));
                break;
            }
            let dst = host(game, &rel);
            if let Err(e) = crate::bundle::safe_rel_path(&rel).and_then(|_| crate::engine_mods::refuse_symlink_path(game, &dst)) {
                blocked = Some(format!("{rel}: {}", e.message));
                break;
            }
            let from = folder.join(src.replace('/', std::path::MAIN_SEPARATOR_STR));
            let b = std::fs::read(&from).map_err(io_at(&from, "reading"))?;
            let sha = crate::hash::sha256_hex(&b);
            targets.push(rel.clone());
            match sha_of(&dst)? {
                None => { ops.push(Op { rel: rel.clone(), before: None, after: Some(sha) }); bytes.insert(rel, b); }
                // A departing package's unchanged copy is removed first, then republished for this package.
                Some(have) if rc.mods.iter().any(|x| x.id != m.id && !wanted.iter().any(|(m, _, _)| m.id == x.id)
                    && x.files.iter().any(|(r, s)| r.eq_ignore_ascii_case(&rel) && s == &have)) => {
                    ops.push(Op { rel: rel.clone(), before: None, after: Some(sha) });
                    bytes.insert(rel, b);
                }
                Some(have) if owned_now(&rel, &have) && have == sha => { keep.insert(rel, sha); }
                Some(have) if owned_now(&rel, &have) => {
                    ops.push(Op { rel: rel.clone(), before: Some(have), after: Some(sha) });
                    bytes.insert(rel, b);
                }
                // the same bytes, put there by someone else (the package installed by hand): they serve, and stay theirs
                Some(have) if have == sha => { if is_code(&rel) { same.push(rel); } }
                Some(_) if is_code(&rel) => {
                    let what = crate::pe::classify_proxy(&dst).ok().and_then(|c| c.detail).filter(|_| ext(&rel) == "dll")
                        .map(|d| format!(" ({d})")).unwrap_or_default();
                    blocked = Some(format!("{rel} is in the game folder already{what} and Kiln did not place it; Kiln leaves it as it is"));
                    break;
                }
                Some(_) => theirs.push(rel),
            }
        }
        if let Some(why) = blocked {
            let earlier = if prev.is_some_and(|x| !x.files.is_empty()) { " Its files Kiln placed before stay as they are." } else { "" };
            pf.notes.push(format!("{t}: not placed in the game folder: {why}, so none of this mod's files are placed.{earlier} Remove \
                that file (or the other mod it belongs to) to use this one"));
            held.push(m.id.clone());
            continue;
        }
        for rel in &targets { reserved.insert(rel.to_ascii_lowercase(), t.clone()); }
        // its earlier version's files it does not place again
        if let Some(x) = prev {
            for rel in x.files.keys().filter(|r| targets.iter().any(|t| t.eq_ignore_ascii_case(r))) {
                // a target the new version places again and that is no longer Kiln's: the player's from now on
                if !ops.iter().any(|o| o.rel.eq_ignore_ascii_case(rel)) && !keep.keys().any(|k| k.eq_ignore_ascii_case(rel)) {
                    pf.released.push((m.id.clone(), rel.clone()));
                }
            }
            removals(&mut paths, &m.id, &x.files, &targets, false, &mut pf, &mut ops, &mut keep)?;
        }
        if !theirs.is_empty() && (!ops.is_empty() || !had) {
            pf.notes.push(format!("{t}: {} in the game folder already and differ from the package's; Kiln leaves them as they are \
                (your settings): {}", if theirs.len() == 1 { "this file is" } else { "these files are" }, names(&theirs)));
        }
        if !same.is_empty() && (!ops.is_empty() || !had) {
            pf.notes.push(format!("{t}: {} in the game folder already with the same content, put there by hand: {} yours, \
                so Kiln does not remove {} when the mod is off ({})", if same.len() == 1 { "this file is" } else { "these files are" },
                if same.len() == 1 { "it stays" } else { "they stay" }, if same.len() == 1 { "it" } else { "them" }, names(&same)));
        }
        let written: Vec<String> = ops.iter().filter(|o| o.after.is_some()).map(|o| o.rel.clone()).collect();
        let done = (!written.is_empty()).then(|| match p.shape {
            Shape::Loader => {
                let loader = p.loader.as_deref().unwrap_or("its loader");
                let stem = loader.strip_suffix(".dll").or_else(|| loader.strip_suffix(".DLL")).unwrap_or(loader).to_ascii_lowercase();
                format!("{t}: Kiln placed {} file(s) of it in the game folder ({}): the game loads {loader} itself; Kiln removes \
                    them again when the mod is off. Under Wine or Proton the game takes it only with a DLL override (Steam launch \
                    option WINEDLLOVERRIDES=\"dinput8,{stem}=n,b\" %command%)", written.len(), names(&written))
            }
            Shape::Asi => format!("{t}: Kiln placed {} file(s) of it in the game folder ({}), for Ultimate ASI Loader ({UAL_FILE}, \
                chained by Kiln's proxy); Kiln removes them again when the mod is off", written.len(), names(&written)),
        });
        if ops.is_empty() && had { pf.kept.push(t); }
        let owner = Owner::Mod { id: m.id.clone(), version: m.version.clone(), hash: m.hash.clone(), shape: p.shape,
            loader: p.loader.as_ref().map(|l| paths.spelled(l)).transpose()? };
        pf.jobs.push(Job { intent: Intent { tag: new_tag()?, owner, ops }, bytes, keep, done, removal: false });
    }

    // Kiln's placements the profile does not want (off, gone, not placeable now, another kind of package): they go
    for x in &rc.mods {
        if held.contains(&x.id) || pf.jobs.iter().any(|j| matches!(&j.intent.owner, Owner::Mod { id, .. } if *id == x.id)) {
            continue;
        }
        let (mut ops, mut keep) = (Vec::new(), BTreeMap::new());
        removals(&mut paths, &x.id, &x.files, &[], true, &mut pf, &mut ops, &mut keep)?;
        let owner = Owner::Mod { id: x.id.clone(), version: x.version.clone(), hash: x.hash.clone(), shape: x.shape, loader: x.loader.clone() };
        // the removals first: a folder one package leaves is free for the next one
        pf.jobs.insert(0, Job { intent: Intent { tag: new_tag()?, owner, ops }, bytes: BTreeMap::new(), keep, done: None, removal: true });
    }
    Ok(pf)
}

/// Runs one job: its intent recorded first (when it changes any file), then each file, then the receipt committed.
/// A stop in between leaves the intent for [`recover`]. Returns whether the files ended as planned.
fn run(game: &Path, rc: &mut Receipts, job: Job, rep: &mut GameFilesReport) -> Result<bool> {
    let Job { intent, bytes, keep, done, removal } = job;
    if !intent.ops.is_empty() {
        rc.pending.push(intent.clone());
        save_receipts(game, rc)?;
    }
    let mut ok = true;
    let mut files = keep;
    for (i, op) in intent.ops.iter().enumerate() {
        #[cfg(test)]
        if STOP_AFTER.with(|s| s.get()) == Some(i) { return Err(Error::invalid("injected stop")); }
        let _ = i;
        let outcome = match (&op.before, &op.after) {
            (None, Some(_)) => put_new(game, &op.rel, &bytes[&op.rel], &intent.tag)?,
            (Some(old), after) => swap(game, &op.rel, old, after.as_ref().map(|_| bytes[&op.rel].as_slice()), &intent.tag)?,
            (None, None) => Outcome::Done,
        };
        match outcome {
            Outcome::Done => if let Some(sha) = &op.after { files.insert(op.rel.clone(), sha.clone()); },
            Outcome::Changed if is_code(&op.rel) => {
                ok = false;
                if let Some(old) = &op.before { files.insert(op.rel.clone(), old.clone()); }
                rep.retained.push(RetainedPlacement { path: host(game, &op.rel), may_run: true, off: op.after.is_none(), reason: format!(
                    "{}: changed while Kiln placed files; Kiln neither replaces nor removes it", owner_label(&intent.owner)) });
            }
            Outcome::Changed | Outcome::Taken => {
                ok = false;
                rep.notes.push(format!("{}: {} changed in the game folder while Kiln placed files; Kiln left it as it is",
                    owner_label(&intent.owner), op.rel));
            }
        }
    }
    #[cfg(test)]
    if STOP_AFTER.with(|s| s.get()) == Some(intent.ops.len()) { return Err(Error::invalid("injected stop before commit")); }
    rc.pending.retain(|p| p.tag != intent.tag);
    match &intent.owner {
        Owner::Ual { from } => {
            rc.ual = intent.ops.first().and_then(|op| files.get(&op.rel).cloned()).map(|sha256| PlacedUal { from: from.clone(), sha256 });
        }
        Owner::Mod { id, version, hash, shape, loader } => {
            rc.mods.retain(|x| x.id != *id);
            if !removal {
                rc.mods.push(Placed { id: id.clone(), version: version.clone(), hash: hash.clone(), shape: *shape, loader: loader.clone(), files });
            } else if !files.is_empty() {
                // a removal that left changed code files: their lines stay, so a later activation still sees them
                rc.mods.push(Placed { id: id.clone(), version: version.clone(), hash: hash.clone(), shape: *shape, loader: loader.clone(), files });
            }
        }
    }
    rc.cleanup.extend(intent.ops.iter().map(|op| Cleanup { rel: op.rel.clone(), tag: intent.tag.clone() }));
    save_receipts(game, rc)?;
    finish_cleanup(game, rc)?;
    if let Some(d) = done.filter(|_| ok) { rep.notes.push(d); }
    Ok(ok)
}

fn owner_label(o: &Owner) -> String {
    match o {
        Owner::Mod { id, .. } => tag(id),
        Owner::Ual { .. } => format!("Ultimate ASI Loader ({UAL_FILE})"),
    }
}

/// Refuse known write failures before removing an outgoing package. Probes are journaled too.
fn check_changes(game: &Path, rc: &mut Receipts, jobs: &[Job]) -> Result<()> {
    let mut folders = std::collections::BTreeSet::new();
    for op in jobs.iter().flat_map(|j| &j.intent.ops) {
        let path = host(game, &op.rel);
        // Windows refuses deleting a read-only file. Unix uses the parent folder's permissions instead.
        if cfg!(windows) && op.before.is_some() && std::fs::metadata(&path).map_err(io_at(&path, "inspecting"))?.permissions().readonly() {
            return Err(Error::new(ErrorCode::Refused, format!(
                "{}: is read-only; make it writable before changing game-folder mods", path.display())));
        }
        if op.after.is_some() {
            let parent = op.rel.rsplit_once('/').map(|(p, _)| p).unwrap_or("");
            folders.insert(parent.to_string());
        }
    }
    if folders.is_empty() { return Ok(()); }
    let probes: Vec<Cleanup> = folders.into_iter().map(|p| Ok(Cleanup {
        rel: if p.is_empty() { ".kiln-check".into() } else { format!("{p}/.kiln-check") }, tag: new_tag()?,
    })).collect::<Result<_>>()?;
    rc.cleanup.extend(probes.iter().cloned());
    save_receipts(game, rc)?;
    let checked = probes.iter().try_for_each(|p| stage(&host(game, &p.rel), &p.tag, b"").map(|_| ()));
    let cleaned = finish_cleanup(game, rc);
    checked.and(cleaned)
}

/// Places the files of the profile's enabled native mods that run from the game folder ([`plan`]) and takes out the
/// ones of Kiln's earlier placements that the profile no longer has on. Called by profile activation before chain.ini
/// is written (that names UAL, [`ual_chain_entry`]). Writes no state when there is nothing to place and nothing placed.
pub fn place(dirs: &DataDirs, profile: &crate::profile::Profile, game: &Path) -> Result<GameFilesReport> {
    place_mods(dirs, &profile.mods.native, game)
}

/// [`place`] for a list of native entries (an activation's rollback puts back the packages placed before it, [`placed`]).
pub fn place_mods(dirs: &DataDirs, mods: &[ProfileMod], game: &Path) -> Result<GameFilesReport> {
    let mut rep = GameFilesReport::default();
    if wanted_of(dirs, mods).is_empty() && std::fs::symlink_metadata(receipts_path(game)).is_err() {
        return Ok(rep);
    }
    let _lock = lock(game)?;
    let mut rc = read_receipts(game)?;
    recover(game, &mut rc, &mut rep)?;
    let pf = preflight(dirs, mods, game, &rc)?;
    check_changes(game, &mut rc, &pf.jobs)?;
    rep.notes.extend(pf.notes);
    rep.retained.extend(pf.retained);
    rep.kept.extend(pf.kept);
    for (id, rel) in &pf.released {
        if let Some(x) = rc.mods.iter_mut().find(|x| x.id == *id) { x.files.retain(|r, _| r != rel); }
    }
    if pf.drop_ual { rc.ual = None; }
    save_receipts(game, &rc)?;
    // a .asi package placed only while its Ultimate ASI Loader could be: a UAL write that did not happen holds them
    let mut ual_failed = false;
    for job in pf.jobs {
        let t = match &job.intent.owner { Owner::Mod { id, .. } => Some(tag(id)), Owner::Ual { .. } => None };
        if ual_failed && matches!(&job.intent.owner, Owner::Mod { shape: Shape::Asi, .. }) && !job.removal {
            rep.notes.push(format!("{}: not placed: Ultimate ASI Loader could not be placed", t.clone().unwrap_or_default()));
            continue;
        }
        let (removal, writes, is_ual) = (job.removal, job.intent.ops.iter().any(|o| o.after.is_some()),
            matches!(job.intent.owner, Owner::Ual { .. }));
        let changes = !job.intent.ops.is_empty();
        let ok = run(game, &mut rc, job, &mut rep)?;
        if is_ual && writes && !ok { ual_failed = true; }
        if let Some(t) = t {
            if removal { rep.removed.push(t); } else if changes { rep.placed.push(t); }
        }
    }
    Ok(rep)
}

/// Would [`place`] change any file for `mods` (play once must not: these files are fixed for a single start)? Read only.
pub fn would_change(dirs: &DataDirs, mods: &[ProfileMod], game: &Path) -> Result<bool> {
    if wanted_of(dirs, mods).is_empty() && std::fs::symlink_metadata(receipts_path(game)).is_err() {
        return Ok(false);
    }
    let rc = read_receipts(game)?;
    if !rc.pending.is_empty() { return Ok(true); }
    let wanted = wanted_of(dirs, mods);
    // A blocked replacement or a retained changed loader can need a different selection without any safe file ops.
    if wanted.len() != rc.mods.len() || wanted.iter().any(|(m, _, _)| !rc.mods.iter()
        .any(|p| p.id == m.id && p.version == m.version && p.hash == m.hash)) {
        return Ok(true);
    }
    Ok(preflight(dirs, mods, game, &rc)?.jobs.iter().any(|j| !j.intent.ops.is_empty()))
}

/// The packages Kiln's receipts say are placed now, as profile entries (an activation's rollback point).
pub(crate) fn placed(game: &Path) -> Result<Vec<ProfileMod>> {
    if std::fs::symlink_metadata(receipts_path(game)).is_err() { return Ok(Vec::new()); }
    let _lock = lock(game)?;
    let mut rc = read_receipts(game)?;
    recover(game, &mut rc, &mut GameFilesReport::default())?;
    Ok(rc.mods.into_iter().map(|x| ProfileMod { id: x.id, version: x.version, hash: x.hash, enabled: true }).collect())
}

/// The loaders Kiln placed that the game loads itself, `(native:<id>, file)`: they run in every start, also one without
/// mods (play-once vanilla and no-mods change only what Kiln's proxy loads).
pub(crate) fn loaders_in_game(game: &Path) -> Result<Vec<(String, String)>> {
    let rc = read_receipts(game)?;
    if !rc.pending.is_empty() {
        return Err(Error::new(ErrorCode::Refused, "A game-folder change was interrupted; activate the profile again before starting without mods"));
    }
    let mut loaders = Vec::new();
    for x in rc.mods.iter().filter(|x| x.shape == Shape::Loader) {
        let Some(file) = x.loader.clone().or_else(|| x.files.keys().find(|r| !r.contains('/') && ext(r) == "dll").cloned()) else { continue };
        crate::bundle::safe_rel_path(&file)?;
        let file = spelled(game, &file)?;
        let path = host(game, &file);
        crate::engine_mods::refuse_symlink_path(game, &path)?;
        if sha_of(&path)?.is_some() { loaders.push((tag(&x.id), file)); }
    }
    Ok(loaders)
}

/// Takes every file Kiln placed in the game folder out again (profile deactivated, Kiln uninstalled), as [`place`]
/// does for a mod that is off: Kiln's unchanged files go, changed code files stay as retained placements, changed
/// settings files stay. Writes nothing in a game Kiln placed nothing in.
pub fn unplace(game: &Path) -> Result<crate::engine_mods::PlacementCleanup> {
    let mut out = crate::engine_mods::PlacementCleanup::default();
    if std::fs::symlink_metadata(receipts_path(game)).is_err() {
        return Ok(out);
    }
    let _lock = lock(game)?;
    let mut rc = read_receipts(game)?;
    let mut rep = GameFilesReport::default();
    recover(game, &mut rc, &mut rep)?;
    let mut paths = CasePaths::new(game);
    let mut pf = Preflight { jobs: Vec::new(), notes: Vec::new(), retained: Vec::new(), released: Vec::new(), kept: Vec::new(), drop_ual: false };
    for x in rc.mods.clone() {
        let (mut ops, mut keep) = (Vec::new(), BTreeMap::new());
        removals(&mut paths, &x.id, &x.files, &[], true, &mut pf, &mut ops, &mut keep)?;
        let owner = Owner::Mod { id: x.id.clone(), version: x.version.clone(), hash: x.hash.clone(), shape: x.shape, loader: x.loader.clone() };
        pf.jobs.push(Job { intent: Intent { tag: new_tag()?, owner, ops }, bytes: BTreeMap::new(), keep, done: None, removal: true });
    }
    if let Some(u) = rc.ual.clone() {
        let rel = paths.spelled(UAL_FILE)?;
        let path = host(game, &rel);
        match sha_of(&path)? {
            Some(have) if have == u.sha256 => pf.jobs.push(Job { intent: Intent { tag: new_tag()?, owner: Owner::Ual { from: u.from },
                ops: vec![Op { rel, before: Some(have), after: None }] }, bytes: BTreeMap::new(),
                keep: BTreeMap::new(), done: None, removal: true }),
            Some(_) => {
                out.retained.push(RetainedPlacement { path, may_run: true, off: true, reason: format!(
                    "Ultimate ASI Loader ({UAL_FILE}) changed since Kiln placed it; Kiln neither replaces nor removes it") });
                rc.ual = None;
            }
            None => rc.ual = None,
        }
    }
    check_changes(game, &mut rc, &pf.jobs)?;
    for (id, rel) in &pf.released {
        if let Some(x) = rc.mods.iter_mut().find(|x| x.id == *id) { x.files.retain(|r, _| r != rel); }
    }
    for job in pf.jobs {
        let before: Vec<PathBuf> = job.intent.ops.iter().map(|o| host(game, &o.rel)).collect();
        run(game, &mut rc, job, &mut rep)?;
        out.removed.extend(before.into_iter().filter(|f| std::fs::symlink_metadata(f).is_err()));
    }
    save_receipts(game, &rc)?;
    out.retained.extend(pf.retained);
    out.retained.extend(rep.retained);
    out.kept_files.extend(pf.notes);
    out.kept_files.extend(rep.notes);
    Ok(out)
}

/// The `kiln/chain.ini` `[profile]` line that loads Ultimate ASI Loader for the profile's `.asi` packages: (the id of
/// the package it is for, [`UAL_CHAIN_LINE`]). Some when an enabled `.asi` package of the profile is placed
/// ([`RECEIPTS`]), UAL is at [`UAL_FILE`], and `[chain]` does not load it already (Kiln's installer chained it there).
pub fn ual_chain_entry(dirs: &DataDirs, profile: &crate::profile::Profile, game: &Path) -> Option<(String, String)> {
    let rc = read_receipts(game).ok()?;
    let placed = |id: &str| rc.mods.iter().any(|p| p.id == id && p.shape == Shape::Asi);
    let asi: Vec<(&ProfileMod, GamePlan)> = profile.mods.native.iter().filter(|m| m.enabled && placed(&m.id))
        .filter_map(|m| plan_of(dirs, m).filter(|p| p.shape == Shape::Asi).map(|p| (m, p))).collect();
    let (first, _) = asi.first()?;
    if !is_ual_at(&host(game, &spelled(game, UAL_FILE).ok()?)) { return None; }
    let chained = crate::chain::read(game).is_ok_and(|ini| ini.chain.iter()
        .any(|e| e.status == crate::chain::EntryStatus::Ok && e.path.eq_ignore_ascii_case(UAL_CHAIN_LINE)));
    if chained { return None; }
    // the line goes with the package that brings UAL, else the first .asi package
    let owner = asi.iter().find(|(_, p)| p.ual.is_some()).map(|(m, _)| *m).unwrap_or(first);
    Some((owner.id.clone(), UAL_CHAIN_LINE.to_string()))
}

/// The chain.ini `[profile]` line Kiln writes for Ultimate ASI Loader ([`ual_chain_entry`]), with UAL at [`UAL_FILE`]: the
/// launch options check asks for the `xinput9_1_0` override for it too (game::launch_options_info). A `[profile]` line
/// for a file of that name that is not UAL is not this.
pub fn ual_in_profile_section(ini: &crate::chain::ChainIni, game: &Path) -> bool {
    ini.profile.iter().any(|e| e.status == crate::chain::EntryStatus::Ok && e.path.eq_ignore_ascii_case(UAL_CHAIN_LINE))
        && spelled(game, UAL_FILE).is_ok_and(|rel| is_ual_at(&host(game, &rel)))
}

// ---- the Library: .asi packages ----

/// An `.asi` package for the Library ([`DetectKind::Asi`], imported by [`import_asi`] as a native mod): a folder that is
/// no other kind of mod, with Ultimate ASI Loader directly in it and/or `.asi` plugins in it or in a folder of it
/// (Smart Workshop's client file is a `Scripts` folder). A folder with another DLL at its top (a native DLL mod that
/// also ships an `.asi` build of itself) is not one: it keeps the native route, which loads that DLL. `top_name`: what
/// the package is called when `dir` is an unpacked archive at depth 0.
pub fn detect_asi_package(dir: &Path, depth: usize, top_name: Option<&str>) -> Option<Detected> {
    if crate::engines::is_container(dir) { return None; }
    let entries: Vec<PathBuf> = std::fs::read_dir(dir).ok()?.flatten().map(|e| e.path()).filter(|p| !p.is_symlink()).collect();
    let is_asi = |p: &Path| p.is_file() && p.extension().is_some_and(|x| x.eq_ignore_ascii_case("asi"));
    // OptiScaler renamed OptiScaler.asi (for Ultimate ASI Loader), in the folder or a folder of it: the tool, which runs
    // on its own next to Kiln, left out whole as a lone OptiScaler.asi is (engines::detect_file), never a package Kiln
    // places in scripts\ and loads
    let optiscaler = |p: &Path| is_asi(p) && p.file_name().is_some_and(|n| crate::engines::is_optiscaler_name(&n.to_string_lossy()));
    let optiscaler_asi = entries.iter().find(|p| optiscaler(p)).cloned().or_else(|| entries.iter().filter(|p| p.is_dir())
        .find_map(|p| std::fs::read_dir(p).into_iter().flatten().flatten().map(|e| e.path()).find(|q| optiscaler(q))));
    if let Some(p) = optiscaler_asi {
        let file = p.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
        return Some(Detected { kind: DetectKind::Proxy, path: dir.display().to_string(), id: None, version: None, name: None,
            reason: crate::engines::loader_reason(crate::engines::Engine::OptiScaler, &file), items: vec![], asi_omit: vec![],
            engine: Some(crate::engines::Engine::OptiScaler) });
    }
    let asi = entries.iter().any(|p| is_asi(p) || (p.is_dir() && std::fs::read_dir(p).into_iter().flatten().flatten().any(|e| is_asi(&e.path()))));
    let dlls = crate::engines::dlls_in(dir);
    let ual = dlls.iter().any(|d| is_ual_at(d));
    if (!asi && !ual) || dlls.iter().any(|d| !is_ual_at(d)) { return None; }
    let name = match (depth, top_name) {
        (0, Some(n)) => crate::library::package_stem(n).to_string(),
        _ => dir.file_name()?.to_string_lossy().into_owned(),
    };
    let id = if asi { crate::library::id_from_name(&name) } else { UAL_ID.to_string() };
    Some(Detected { kind: DetectKind::Asi, path: dir.display().to_string(), id: Some(id), version: Some("0.0.0".into()),
        name: Some(if asi { name } else { UAL_NAME.to_string() }), reason: ASI_REASON.into(), items: vec![], asi_omit: vec![],
        engine: Some(crate::engines::Engine::UltimateAsiLoader) })
}

/// The Library id of Ultimate ASI Loader on its own: one entry whatever the download is called, so a newer UAL replaces
/// the one in the profile.
pub const UAL_ID: &str = "ultimate-asi-loader";
const UAL_NAME: &str = "Ultimate ASI Loader";
/// Why an `.asi` package or Ultimate ASI Loader is a Library mod.
pub const ASI_REASON: &str = "Ultimate ASI Loader or its .asi plugins: added as a native mod, placed in the game folder while it \
    is on (Ultimate ASI Loader as xinput9_1_0.dll next to Kiln's dinput8.dll, the plugins in scripts)";

/// Imports an [`DetectKind::Asi`] item (a package folder, a lone `.asi` file, or a lone Ultimate ASI Loader DLL) as a
/// native mod: its files as they are, and a generated native.json that lists Ultimate ASI Loader under `dlls` when the
/// package brings it and the plugins under `asi`. kiln-core never loads it ([`plan`]): activation places it.
pub fn import_asi(ctx: &mut crate::engines::ImportCtx) -> Result<()> {
    let (dirs, d, src) = (ctx.dirs, ctx.detected, ctx.src);
    let tmp = crate::library::TempDir::new(&dirs.library(), "import")?;
    let work = tmp.path().join("m");
    let file_name = src.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
    let mut size = if src.is_dir() {
        let size = crate::library::copy_mod_tree(src, &work)?;
        if crate::hash::dirhash(&work)? != crate::hash::dirhash(src)? {
            return Err(Error::new(ErrorCode::HashMismatch, "It changed while it was imported."));
        }
        size
    } else {
        std::fs::create_dir_all(&work).map_err(io_at(&work, "creating"))?;
        std::fs::copy(src, work.join(&file_name)).map_err(io_at(src, "copying"))?
    };
    // A Scripts folder can hold this mod's .asi and someone else's. Only the matching file is left out.
    // The omitted files are named as `d.path` is (a zip's entry as `<zip>/<entry>`), so their place in the package is
    // taken relative to it, and `skipped` shows the path the player knows.
    if src.is_dir() {
        for omit in &d.asi_omit {
            let Ok(rel) = Path::new(&omit.path).strip_prefix(&d.path) else { continue };
            if rel.as_os_str().is_empty() || rel.components().any(|c| !matches!(c, std::path::Component::Normal(_))) {
                continue;
            }
            let (file, id) = (&omit.path, &omit.native_id);
            let in_work = work.join(rel);
            if !in_work.is_file() {
                continue;
            }
            let len = std::fs::metadata(&in_work).map(|m| m.len()).unwrap_or(0);
            if std::fs::remove_file(&in_work).is_ok() {
                size = size.saturating_sub(len);
                ctx.report.skipped.push(crate::library::Skipped {
                    path: file.clone(),
                    reason: format!("the same mod is already this package's Kiln native mod ({id}): only that one is added, so it is not also loaded as an .asi"),
                });
            }
        }
    }
    let files = files_of(&work).ok_or_else(|| Error::new(ErrorCode::Refused, "links or too many files in the package"))?;
    let ual = ual_in(&work, &files);
    let asi: Vec<String> = files.iter().filter(|f| ext(f) == "asi").cloned().collect();
    if ual.is_none() && asi.is_empty() {
        ctx.report.skipped.push(crate::library::Skipped { path: d.path.clone(), reason: "no .asi plugin and no Ultimate ASI Loader in it".into() });
        return Ok(());
    }
    let stem = |n: &str| Path::new(n).file_stem().map(|s| s.to_string_lossy().into_owned()).unwrap_or_else(|| n.to_string());
    let (id, name) = match (src.is_dir(), asi.is_empty()) {
        (_, true) => (UAL_ID.to_string(), UAL_NAME.to_string()),
        (false, false) => (crate::library::id_from_name(&stem(&file_name)), stem(&file_name)),
        (true, false) => (d.id.clone().unwrap_or_else(|| crate::library::id_from_name(&file_name)), d.name.clone().unwrap_or(file_name.clone())),
    };
    let version = ual.as_ref().and_then(|u| std::fs::read(work.join(u)).ok()).filter(|_| asi.is_empty())
        .and_then(|b| crate::library::dll_file_version(&b)).unwrap_or_else(|| "0.0.0".into());
    let manifest = serde_json::json!({
        "format": 1, "id": id, "name": name, "version": version,
        "description": format!("Generated by Kiln: {}. Kiln places it in the game folder while it is on; kiln-core does not load it",
            match (&ual, asi.len()) {
                (Some(_), 0) => "Ultimate ASI Loader".to_string(),
                (Some(_), n) => format!("Ultimate ASI Loader and {n} .asi plugin(s)"),
                (None, n) => format!("{n} .asi plugin(s) for Ultimate ASI Loader"),
            }),
        "side": "client", "dlls": ual.iter().collect::<Vec<_>>(), "asi": asi,
    });
    let mut body = serde_json::to_string_pretty(&manifest)?;
    body.push('\n');
    size += body.len() as u64;
    std::fs::write(work.join(crate::manifest::NATIVE_MANIFEST), body).map_err(io_at(&work, "writing"))?;
    crate::manifest::read_native(&work)?;
    let hash = crate::hash::dirhash(&work)?;
    let rec = ImportRecord { format: 1, kind: ModKind::Native, id, version, hash, imported: crate::util::now_rfc3339(),
        source: Some(ctx.from.clone()), size, name: Some(name), side: Some(Side::Client), clients: Some(Clients::Mod), file: None,
        manifest_id: None, game_folder: None, loader_part: None };
    crate::library::commit_folder(dirs, &work, rec, ctx.report)
}


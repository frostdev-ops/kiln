#[derive(Debug, Clone, Default, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
struct Receipts {
    format: u32,
    #[serde(default)]
    mods: Vec<Placed>,
    /// Ultimate ASI Loader as [`UAL_FILE`], when Kiln placed it (from the package `from`).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    ual: Option<PlacedUal>,
    /// Changes begun and not yet committed, written before their first file changes ([`run`]); [`recover`] settles them.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pending: Vec<Intent>,
    /// Side files of committed work stay recorded until their cleanup commits too.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    cleanup: Vec<Cleanup>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
struct Cleanup {
    rel: String,
    tag: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
struct Placed {
    id: String,
    version: String,
    hash: String,
    shape: Shape,
    /// The loader DLL of a [`Shape::Loader`] package, game-relative (what the game loads even in a start without mods).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    loader: Option<String>,
    /// Game-relative file ('/'-separated) -> the sha256 Kiln wrote.
    files: BTreeMap<String, String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
struct PlacedUal {
    from: String,
    sha256: String,
}

/// The changes of one package (or of Ultimate ASI Loader) as they are about to happen.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
struct Intent {
    /// Names the files staged and moved aside for it (`.<name>.<tag>.kiln-new` / `.kiln-old`, next to the file).
    tag: String,
    owner: Owner,
    ops: Vec<Op>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "kebab-case")]
enum Owner {
    #[serde(rename_all = "camelCase")]
    Mod { id: String, version: String, hash: String, shape: Shape, #[serde(default, skip_serializing_if = "Option::is_none")] loader: Option<String> },
    Ual { from: String },
}

/// One file: Kiln's bytes there before (None: no file), and after (None: Kiln removes it).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
struct Op {
    rel: String,
    #[serde(default)]
    before: Option<String>,
    #[serde(default)]
    after: Option<String>,
}

fn receipts_path(game: &Path) -> PathBuf {
    RECEIPTS.split('/').fold(game.to_path_buf(), |p, c| p.join(c))
}

fn read_receipts(game: &Path) -> Result<Receipts> {
    let file = receipts_path(game);
    crate::engine_mods::refuse_symlink_path(game, &file)?;
    Ok(crate::util::read_json::<Receipts>(&file)?.unwrap_or_default())
}


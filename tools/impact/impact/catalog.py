"""Natives, impact types and the config vocabulary.

Files (tools/impact/data, generated by `impact.py survey` from the installed game, then documented by hand):
    natives.json        the 108 vanilla registrations (107 distinct hashes) with signatures from evidence
    kiln-natives.json   Kiln's built-in natives (kiln.Log, kiln.Signal), registered by kiln.abilities
    types.json          the impact types used by vanilla programs: impact name, hash, size, and a reflection
                        closure (tools/kfc TypeDb dump shape) for typed initial values
    configs.json        the config vocabulary: config id -> variable names, type, use count

A mod declares its own natives in impact/natives.json (same schema as natives.json, `format` 1). The contract with
kiln.abilities (docs/kiln/modding/impact.md):
    name   "<modid>.<Name>", Name [A-Za-z0-9_]; mod id "kiln" is reserved for Kiln's built-ins
    hash   FNV-1a-32 over the full UTF-8 name (vanilla: of the node name, e.g. "ApplyDamage" = 0xb04d0e7a)
    argc   0..31; args[] listed in args[] index order: args[0] is the LAST value pushed before the ECALL
"""
import json
import re
from pathlib import Path

from .program import fnv1a32

DATA = Path(__file__).resolve().parent.parent / "data"


def _data_dir():
    """tools/impact/data, or the survey output in $KILN_OUT/impact-data when the repo copy is absent."""
    import os
    if (DATA / "natives.json").exists():
        return DATA
    alt = Path(os.environ.get("KILN_OUT") or (Path(__file__).resolve().parents[3] / ".out/impact")) / "impact-data"
    return alt if (alt / "natives.json").exists() else DATA
NAME_RX = re.compile(r"^[A-Za-z0-9_\-]+\.[A-Za-z0-9_]+$")


class CatalogError(Exception):
    pass


def _h(x):
    if isinstance(x, int):
        return x
    return int(str(x), 0)


class Param:
    __slots__ = ("name", "types", "dir", "doc", "optional", "raw", "unchecked", "always")

    def __init__(self, name, types=(), dir="in", doc="", optional=False, raw=False, unchecked=False, always=False):
        self.name, self.types, self.dir, self.doc, self.optional = name, list(types), dir, doc, optional
        self.raw = raw  # the native accepts a raw integer here (not only a variable handle)
        self.unchecked = unchecked  # the native reads it without a null check: unconnected, it faults and the process dies
        self.always = always  # every vanilla call connects it

    @classmethod
    def from_json(cls, d):
        t = d.get("types", d.get("type", []))
        if isinstance(t, str):
            t = [t]
        ev = d.get("evidence") or {}
        always = d.get("dir", "in") == "in" and ev.get("unconnected") == 0 and ev.get("connected", 0) > 0
        return cls(d.get("name", ""), t, d.get("dir", "in"), d.get("doc", ""), bool(d.get("optional", False)),
                   bool(d.get("raw", False)), bool(d.get("unchecked", False)), always)


class Native:
    __slots__ = ("hash", "name", "node", "argc", "args", "returns", "suspends", "doc", "origin", "extra")

    def __init__(self, hash, name, argc, node=None, args=None, returns="", suspends=False, doc="", origin="vanilla",
                 extra=None):
        self.hash, self.name, self.argc = hash, name, argc
        self.node = node or name
        self.args = args or []
        self.returns, self.suspends, self.doc, self.origin = returns, suspends, doc, origin
        self.extra = extra or {}

    @classmethod
    def from_json(cls, d, origin):
        name = d["name"]
        h = _h(d["hash"]) if "hash" in d else fnv1a32(d.get("node", name))
        args = [Param.from_json(a) for a in d.get("args", [])]
        argc = int(d["argc"]) if "argc" in d else len(args)
        return cls(h, name, argc, d.get("node"), args, d.get("returns", ""), d.get("suspends", False),
                   d.get("doc", ""), origin, {k: v for k, v in d.items() if k not in (
                       "hash", "name", "node", "argc", "args", "returns", "suspends", "doc")})

    def param(self, i):
        return self.args[i] if i < len(self.args) else None

    def __repr__(self):
        return f"Native({self.name} {self.hash:#010x} argc {self.argc} {self.origin})"


class Catalog:
    def __init__(self):
        self.natives = {}           # hash -> Native
        self._by_name = {}          # name / node / lower-case -> Native
        self.types = {}             # impact type hash -> {name, qualified, size, align}
        self.type_by_name = {}
        self.records = None         # kfc TypeDb (closure of the impact types) or None
        self.configs = {}           # config id -> {names, type, programs}
        self.config_alias = {}      # alias -> id
        self.problems = []          # declaration problems (collisions, bad names)

    # ---- loading
    @classmethod
    def default(cls, extra_natives=(), with_records=True):
        c = cls()
        d = _data_dir()
        if (d / "natives.json").exists():
            c.add_natives(json.loads((d / "natives.json").read_text()), "vanilla")
        if (DATA / "kiln-natives.json").exists():
            c.add_natives(json.loads((DATA / "kiln-natives.json").read_text()), "kiln")
        if (d / "types.json").exists():
            c.add_types(json.loads((d / "types.json").read_text()), with_records)
        if (d / "configs.json").exists():
            c.add_configs(json.loads((d / "configs.json").read_text()))
        for p in extra_natives:
            c.add_natives_file(p)
        return c

    def add_natives_file(self, path, origin=None):
        p = Path(path)
        doc = json.loads(p.read_text())
        return self.add_natives(doc, origin or f"mod:{p}")

    def add_natives(self, doc, origin):
        if doc.get("format", 1) != 1:
            raise CatalogError(f"{origin}: natives format {doc.get('format')!r}, expected 1")
        added = []
        for d in doc.get("natives", []):
            n = Native.from_json(d, origin)
            if origin != "vanilla":
                self._check_declared(n)
            old = self.natives.get(n.hash)
            if old is not None and old.origin != origin:
                self.problems.append(f"{n.name} ({n.hash:#010x}, {origin}) collides with {old.name} ({old.origin})")
                continue
            if old is not None and origin == "vanilla":
                continue  # the duplicate registration (ChangeAttribute is registered twice)
            self.natives[n.hash] = n
            for k in {n.name, n.node}:
                self._by_name.setdefault(k, n)
                self._by_name.setdefault(k.lower(), n)
            added.append(n)
        return added

    def _check_declared(self, n):
        if not NAME_RX.match(n.name):
            self.problems.append(f"{n.name}: a Kiln native name is '<modid>.<Name>' with Name [A-Za-z0-9_]")
        if n.hash != fnv1a32(n.name):
            self.problems.append(f"{n.name}: hash {n.hash:#010x} != FNV-1a('{n.name}') {fnv1a32(n.name):#010x}")
        if not 0 <= n.argc <= 31:
            self.problems.append(f"{n.name}: argc {n.argc} (0..31)")
        if n.args and len(n.args) != n.argc:
            self.problems.append(f"{n.name}: argc {n.argc} but {len(n.args)} args listed")
        if n.origin != "kiln" and n.name.split(".")[0].lower() == "kiln":
            self.problems.append(f"{n.name}: mod id 'kiln' is reserved for Kiln's built-ins")

    def add_types(self, doc, with_records=True):
        for t in doc.get("impact", []):
            h = _h(t["hash"])
            self.types[h] = t
            self.type_by_name[t["name"]] = t
        if with_records and doc.get("records"):
            from kfc.refl import TypeDb
            self.records = TypeDb({"types": doc["records"]})

    def add_configs(self, doc):
        for c in doc.get("configs", []):
            cid = _h(c["id"])
            self.configs[cid] = c
            for a in c.get("aliases", []):
                self.config_alias.setdefault(a, cid)

    # ---- queries
    def native(self, token):
        """By display name, node name, Kiln name, lower-case name or 0x hash. None when unknown."""
        if isinstance(token, int):
            return self.natives.get(token)
        if token.lower().startswith("0x"):
            return self.natives.get(int(token, 16))
        return self._by_name.get(token) or self._by_name.get(token.lower())

    def type_name(self, h):
        t = self.types.get(h)
        return t["name"] if t else None

    def type_hash(self, token):
        if token.lower().startswith("0x"):
            return int(token, 16)
        return fnv1a32(token)

    def type_info(self, h):
        return self.types.get(h)

    def config_id(self, token):
        """0x literal, a vocabulary alias (Damage, BuffType, ...), or "text" (FNV-1a of the text)."""
        if token.startswith('"') and token.endswith('"'):
            return fnv1a32(token[1:-1])
        if token.lower().startswith("0x"):
            return int(token, 16)
        if token in self.config_alias:
            return self.config_alias[token]
        if token.isdigit():
            return int(token)
        raise CatalogError(f"config {token!r}: not a 0x id, a known alias or a \"string\"")

    def config_name(self, cid):
        c = self.configs.get(cid)
        if not c:
            return None
        al = c.get("aliases") or []
        return al[0] if al else None

"""The docs' C# snippets, compiled: tools/docs-site/snippets.json names pages of the skill and docs/kiln, and how each C#
fence of them compiles; this writes managed/tests/Kiln.DocSnippets.Tests/Generated/<page>.snippets.cs from them (not *.g.cs and no
<auto-generated> mark: Roslyn runs no analyzer on generated code).

  python3 -I tools/docs-site/snippets.py [--check] [--root DIR]

Kiln.DocSnippets.Tests builds those files with the Kiln analyzers and every warning an error, so a snippet that names a
member that is gone, calls with a wrong signature, uses a name it never declared, throws a result away (KILN120) or calls
a capability-gated member unguarded (KILN121) fails the build, at its line in the page (#line). The project runs nothing:
compiling is the check (tools/win1 dotnet <worktree> Kiln.DocSnippets.Tests, and check.sh's build stage).

snippets.json: {"pages": {"<repo path of a .md>": {"cover": "all" | "listed", "fences": {"<n>": <entry>}}}}
  n       the n-th ```csharp (or ```cs, ```c#) fence of the page, from 1
  cover   all: every C# fence of the page has an entry (a new fence fails --check until it has one); listed: only these
  entry   {"skip": "<why it does not compile as it is: a signature listing, ...>"} or
          {"wrap": "file" | "members" | "method" | "test", ...}
            file     the fence is whole type declarations
            members  the fence is members of a Mod class
            method   the fence is statements: the body of `method` (default `public async Task Run()`) in a Mod class;
                     "attrs": attributes of that class, "before": statements before the fence (not the doc's, e.g. the
                     `var registry = Registries.For(context);` a registry page's fragments assume)
            test     statements in a test method of a class (Kiln.TestKit and Xunit in scope), compiled, never run
          "stubs": ["EntityId player", "bool FarFromOwner(PetSnapshot p) => false", ...]: the names the page's text
          declares around the fence, as static members in scope (a property without a body reads `default!`);
          "types": ["public sealed class Settings { ... }"]: types the page assumes; "nowarn": ["KILN121: <why>"]: a
          warning the fence may raise on purpose, with why
--check: exit 1 when a generated file is not current, a covered page has a C# fence without an entry, or an entry names
no fence. Tests: python3 -I tools/docs-site/test_snippets.py
"""
import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MANIFEST = "tools/docs-site/snippets.json"
OUT = "managed/tests/Kiln.DocSnippets.Tests/Generated"
FENCE_RE = re.compile(r"^(\s*)(```+|~~~+)\s*([\w#+-]*)\s*$")
CS = ("csharp", "cs", "c#")
USING_RE = re.compile(r"^\s*using\s+(?:static\s+)?[\w.]+\s*(?:=\s*[\w.<>]+\s*)?;\s*$")
WRAPS = ("file", "members", "method", "test")


class Problem(Exception):
    pass


def cs_fences(text):
    """[(first content line number, [content lines])] of the page's C# fences, in order."""
    out, cur, fence = [], None, None
    for n, line in enumerate(text.splitlines(), 1):
        m = FENCE_RE.match(line)
        if fence is None:
            if m:
                fence = m.group(2)
                cur = (n + 1, []) if m.group(3).lower() in CS else None
            continue
        if m and m.group(2).startswith(fence[0]) and len(m.group(2)) >= len(fence) and not m.group(3):
            if cur is not None:
                out.append(cur)
            fence, cur = None, None
            continue
        if cur is not None:
            cur[1].append(line)
    return out


def dedent(lines):
    ind = [len(l) - len(l.lstrip()) for l in lines if l.strip()]
    k = min(ind) if ind else 0
    return [l[k:] if l.strip() else "" for l in lines]


def slug(page):
    s = re.sub(r"\.md$", "", page)
    s = re.sub(r"^agent/skills/kiln-modding/references/", "skill/", s)
    s = re.sub(r"^docs/kiln/", "docs/", s)
    return re.sub(r"[^A-Za-z0-9]+", "_", s).strip("_")


def stub(s):
    s = s.strip().rstrip(";")
    if "(" in s.split("=>")[0]:
        if s.endswith("}"):
            return f"        public static {s}"
        return f"        public static {s};" if "=>" in s else f"        public static {s} => default!;"
    return f"        public static {s} => default!;"


def emit(page, n, entry, start, lines):
    """the C# of one fence: a namespace block whose body maps back to the page's lines"""
    lines = dedent(lines)
    usings = [l.strip() for l in lines if USING_RE.match(l) and not l.lstrip().startswith("using var")]
    body = ["" if (USING_RE.match(l) and not l.lstrip().startswith("using var")) else l for l in lines]
    ns = f"DocSnippets.{slug(page)}_{n}"
    wrap = entry["wrap"]
    o = [f"namespace {ns}", "{"]
    o += [f"    {u}" for u in usings]
    if wrap == "test":
        o += ["    using Kiln.TestKit;", "    using Xunit;"]
    stubs = entry.get("stubs", [])
    if stubs:
        o += [f"    using static {ns}.Stubs;", "    internal static class Stubs", "    {"]
        o += [stub(s) for s in stubs]
        o += ["    }"]
    o += [f"    {t}" for t in entry.get("types", [])]
    nowarn = [w.split(":")[0].strip() for w in entry.get("nowarn", [])]
    mapped = [f'#line {start} "{page}"'] + body + ["#line default"]
    if nowarn:
        mapped = [f"#pragma warning disable {', '.join(nowarn)}"] + mapped + [f"#pragma warning restore {', '.join(nowarn)}"]
    if wrap == "file":
        o += mapped
    elif wrap == "members":
        o += ["    public sealed partial class Snippet : Mod", "    {"] + mapped + ["    }"]
    elif wrap in ("method", "test"):
        attrs = entry.get("attrs")
        if attrs:
            o += [f"    {attrs}"]
        if wrap == "method":
            o += ["    public sealed partial class Snippet : Mod", "    {"]
            sig = entry.get("method", "public async Task Run()")
        else:
            o += ["    public sealed partial class SnippetTest", "    {"]
            sig = entry.get("method", "public void Run()")
        o += [f"        {sig}", "        {"]
        o += [f"            {b}" for b in entry.get("before", [])]
        o += mapped + ["        }", "    }"]
    o += ["}", ""]
    return o


def generate(root):
    """{file name: text} of the generated files, and the problems of the manifest against the pages"""
    root = Path(root)
    man = json.loads((root / MANIFEST).read_text(encoding="utf-8"))
    files, problems = {}, []
    for page, spec in sorted(man.get("pages", {}).items()):
        p = root / page
        if not p.is_file():
            problems.append(f"{MANIFEST}: {page}: no such page")
            continue
        fences = cs_fences(p.read_text(encoding="utf-8"))
        cover = spec.get("cover", "all")
        if cover not in ("all", "listed"):
            problems.append(f"{MANIFEST}: {page}: cover is all or listed, not {cover!r}")
        entries = spec.get("fences", {})
        for k in entries:
            if not k.isdigit() or not 1 <= int(k) <= len(fences):
                problems.append(f"{MANIFEST}: {page}: fence {k} does not exist (the page has {len(fences)} C# fences)")
        # not "<auto-generated>" and not *.g.cs: Roslyn runs no analyzer on generated code, and the analyzers are the point
        out = ["// Made by tools/docs-site/snippets.py from " + page + ": do not edit; edit the page or",
               "// tools/docs-site/snippets.json and run python3 -I tools/docs-site/snippets.py",
               "#pragma warning disable CS1591", ""]
        any_ = False
        for i, (start, lines) in enumerate(fences, 1):
            e = entries.get(str(i))
            if e is None:
                if cover == "all":
                    problems.append(f"{page}:{start - 1}: C# fence {i} has no entry in {MANIFEST} (a wrap, or a skip with why)")
                continue
            if "skip" in e:
                if not str(e["skip"]).strip():
                    problems.append(f"{MANIFEST}: {page}: fence {i}: a skip says why")
                continue
            if any(":" not in w or not w.split(":", 1)[1].strip() for w in e.get("nowarn", [])):
                problems.append(f"{MANIFEST}: {page}: fence {i}: a nowarn reads \"<id>: <why>\"")
            if e.get("wrap") not in WRAPS:
                problems.append(f"{MANIFEST}: {page}: fence {i}: wrap is one of {', '.join(WRAPS)}")
                continue
            out += emit(page, i, e, start, lines)
            any_ = True
        if any_:
            files[slug(page) + ".snippets.cs"] = "\n".join(out)
    return files, problems


def run(root, check):
    root = Path(root)
    files, problems = generate(root)
    out = root / OUT
    have = {p.name: p for p in out.glob("*.cs")} if out.is_dir() else {}
    stale = []
    for name, text in sorted(files.items()):
        cur = have[name].read_text(encoding="utf-8") if name in have else None
        if cur != text:
            stale.append(name)
            if not check:
                out.mkdir(parents=True, exist_ok=True)
                (out / name).write_text(text, encoding="utf-8")
    for name in sorted(set(have) - set(files)):
        stale.append(name)
        if not check:
            have[name].unlink()
    for p in problems:
        print(p, file=sys.stderr)
    if check and stale:
        print(f"snippets: {len(stale)} generated file(s) not current ({', '.join(stale)}): python3 -I tools/docs-site/snippets.py",
              file=sys.stderr)
    n = sum(t.count("#line default") for t in files.values())
    print(f"snippets: {n} fences in {len(files)} files" + (" current" if check and not stale else "" if check else
                                                          f", {len(stale)} written or removed"))
    return 1 if problems or (check and stale) else 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root", default=str(HERE.parent.parent))
    a = ap.parse_args(argv)
    try:
        return run(a.root, a.check)
    except (Problem, json.JSONDecodeError) as e:
        print(f"snippets: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())

# The first line of every file the generate mode writes. tests/run.py and the Kiln.Game tests look for it: a file that
# starts with it must never be in the tree (only under obj/, bin/ or among the made-up expected outputs).
MARKER = "// kiln-typegen: generated at build time from a game layout dump. Never commit this file."

# The dev.24 types of namespace Kiln.GameTypes, in their dev.24 order (managed/Kiln.Game/Generated.cs).
LEGACY = ["NetworkHealth", "Health", "Mana", "Stamina", "CurrentTransform", "LastTransform", "Velocity",
          "TeleportCount", "NpcCommon"]

# Schema 2 (out/typegen/PLAN.md): the only keys a dump may have, and which must be there.
TOP_KEYS = {"schema", "side", "exe_sha256", "components", "events", "types"}
TYPE_KEYS = {"name", "qualifiedName", "hash", "kind", "size", "align", "inner", "fields", "values"}
TYPE_REQUIRED = {"name", "qualifiedName", "hash", "kind", "size", "align"}
FIELD_KEYS = {"name", "offset", "type"}
VALUE_KEYS = {"name", "value"}

# Reflection kinds (docs/re/content.md §2, native/services/types/scan.h).
K_BOOL, K_ENUM, K_TYPEDEF, K_STRUCT, K_ARRAY, K_REF, K_GUID = 1, 12, 17, 18, 19, 28, 29
PRIMS = {1: ("bool", 1), 2: ("byte", 1), 3: ("sbyte", 1), 4: ("ushort", 2), 5: ("short", 2), 6: ("uint", 4),
         7: ("int", 4), 8: ("ulong", 8), 9: ("long", 8), 10: ("float", 4), 11: ("double", 8)}
INTEGER_KINDS = {2, 3, 4, 5, 6, 7, 8, 9}
SIGNED_KINDS = {3, 5, 7, 9}
MASK_UNDERLYING = {13: ("byte", 1), 14: ("ushort", 2), 15: ("uint", 4), 16: ("ulong", 8)}
LEAF_NAMES = {24: "a blob array (its elements live outside the struct)", 25: "a blob string (its text lives outside the struct)"}
KNOWN_KINDS = set(range(1, 30))

# Members every generated struct has; a game field with one of these names stops the generator.
STRUCT_MEMBERS = {"Hash", "Name", "QualifiedName", "Size", "Layout"}
# The generated methods a mod can bind to, listed in a struct's table line as <name>@method:<C# type> (§3.6).
TABLE_METHODS = {"op_Implicit", "get_Values"}
# Names the hand-written part of the root class uses or keeps for typed access (task access); a generated type with
# one of them stops the generator. Extend this set when a hand-written member of the root class is added.
ROOT_RESERVED = {"ObjectReference", "GameGuid", "Get", "TryGet", "Has", "All", "Available", "NameOf", "Find",
                 "Supports", "WhyNot", "RequireWorld", "Programs",
                 # names the generated code uses unqualified inside the root class: a nested type would hide them
                 "System", "Kiln", "StructLayout", "StructLayoutAttribute", "LayoutKind", "FieldOffset",
                 "FieldOffsetAttribute", "InlineArray", "InlineArrayAttribute", "IGameStruct", "IGameComponent",
                 "IGameEvent", "IGameAttribute", "Span",
                 "Read", "TryRead", "Write", "TryWrite", "Types", "Layouts"}

CS_KEYWORDS = set("""abstract as base bool break byte case catch char checked class const continue decimal default
delegate do double else enum event explicit extern false finally fixed float for foreach goto if implicit in int
interface internal is lock long namespace new null object operator out override params private protected public
readonly ref return sbyte sealed short sizeof stackalloc static string struct switch this throw true try typeof uint
ulong unchecked unsafe ushort using virtual void volatile while""".split())

IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
QNAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*(::[A-Za-z_][A-Za-z0-9_]*)*(<[A-Za-z0-9_:<>,]+>)?$")
HASH = re.compile(r"^0x[0-9A-F]{8}$")
SHA = re.compile(r"^[0-9a-f]{64}$")


class GenError(Exception):
    pass


def qname_tail(qn):
    """The short name of a qualified name: after the last :: outside a template argument list."""
    head = qn.split("<", 1)[0]
    return qn[head.rfind("::") + 2:] if "::" in head else qn


def fnv1a32(s):
    h = 0x811C9DC5
    for b in s.encode("utf-8"):
        h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    return h


def fnv1a64(s):
    h = 0xCBF29CE484222325
    for b in s.encode("utf-8"):
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def cs_id(name):
    return "@" + name if name in CS_KEYWORDS else name


def is_int(v):
    return isinstance(v, int) and not isinstance(v, bool)


def load_dump(path):
    """Reads and checks a schema-2 dump. Raises GenError naming the place of the first problem."""
    try:
        with open(path, "rb") as f:
            d = json.loads(f.read().decode("utf-8"))
    except (OSError, ValueError) as e:
        raise GenError(f"{path}: not a readable JSON dump: {e}")
    where = os.path.basename(path)

    def bad(at, what):
        raise GenError(f"{where}: {at}: {what}")

    if not isinstance(d, dict):
        bad("(root)", "not an object")
    for k in d:
        if k not in TOP_KEYS:
            bad(k, "key outside schema 2")
    for k in sorted(TOP_KEYS):
        if k not in d:
            bad(k, "missing")
    if d["schema"] != 2 or not is_int(d["schema"]):
        bad("schema", f"is {d['schema']!r}; this generator reads schema 2 (schema 1 takes the two-argument legacy mode)")
    if d["side"] not in ("server", "client"):
        bad("side", f"{d['side']!r} is not server or client")
    if not isinstance(d["exe_sha256"], str) or not SHA.match(d["exe_sha256"]):
        bad("exe_sha256", "is not 64 lower-case hex digits")
    if not isinstance(d["types"], list):
        bad("types", "is not a list")
    by = {}
    for i, t in enumerate(d["types"]):
        at = f"types[{i}]"
        if not isinstance(t, dict):
            bad(at, "is not an object")
        if isinstance(t.get("qualifiedName"), str):
            at += f" ({t['qualifiedName']})"
        for k in t:
            if k not in TYPE_KEYS:
                bad(f"{at}.{k}", "key outside schema 2")
        for k in sorted(TYPE_REQUIRED):
            if k not in t:
                bad(f"{at}.{k}", "missing")
        qn = t["qualifiedName"]
        if not isinstance(qn, str) or not QNAME.match(qn):
            bad(f"{at}.qualifiedName", f"{qn!r} is not a type name")
        if not isinstance(t["name"], str) or not QNAME.match(t["name"]) or t["name"] != qname_tail(qn):
            bad(f"{at}.name", f"{t['name']!r} is not the last part of the qualified name ({qname_tail(qn)!r})")
        if not isinstance(t["hash"], str) or not HASH.match(t["hash"]):
            bad(f"{at}.hash", "is not 0x%08X")
        if int(t["hash"], 16) != fnv1a32(qn):
            bad(f"{at}.hash", f"{t['hash']} is not FNV-1a-32 of the qualified name (0x{fnv1a32(qn):08X})")
        for k in ("kind", "size", "align"):
            if not is_int(t[k]) or t[k] < 0:
                bad(f"{at}.{k}", "is not a non-negative integer")
        if t["kind"] not in KNOWN_KINDS:
            bad(f"{at}.kind", f"{t['kind']} is a kind this generator does not know")
        if t["size"] < 1 or t["size"] > (1 << 24):
            bad(f"{at}.size", f"{t['size']} is out of range")
        if t["align"] not in (1, 2, 4, 8, 16, 32, 64):
            bad(f"{at}.align", f"{t['align']} is not a power of two")
        k = t["kind"]
        if "inner" in t:
            if not (12 <= k <= 19):
                bad(f"{at}.inner", f"kind {k} has no inner type in schema 2")
            if not isinstance(t["inner"], str):
                bad(f"{at}.inner", "is not a type name")
        elif 12 <= k <= 17 or k == K_ARRAY:
            bad(f"{at}.inner", f"missing (kind {k} needs one)")
        if "fields" in t:
            if k != K_STRUCT:
                bad(f"{at}.fields", f"kind {k} has no fields in schema 2")
            if not isinstance(t["fields"], list):
                bad(f"{at}.fields", "is not a list")
            for j, f in enumerate(t["fields"]):
                fat = f"{at}.fields[{j}]"
                if not isinstance(f, dict):
                    bad(fat, "is not an object")
                for fk in f:
                    if fk not in FIELD_KEYS:
                        bad(f"{fat}.{fk}", "key outside schema 2")
                for fk in sorted(FIELD_KEYS):
                    if fk not in f:
                        bad(f"{fat}.{fk}", "missing")
                if not isinstance(f["name"], str) or not IDENT.match(f["name"]):
                    bad(f"{fat}.name", f"{f['name']!r} is not an identifier")
                if not is_int(f["offset"]) or f["offset"] < 0:
                    bad(f"{fat}.offset", "is not a non-negative integer")
                if not isinstance(f["type"], str):
                    bad(f"{fat}.type", "is not a type name")
        elif k == K_STRUCT:
            bad(f"{at}.fields", "missing (a struct lists its fields, maybe none)")
        if "values" in t:
            if not (12 <= k <= 16):
                bad(f"{at}.values", f"kind {k} has no values in schema 2")
            if not isinstance(t["values"], list):
                bad(f"{at}.values", "is not a list")
            for j, v in enumerate(t["values"]):
                vat = f"{at}.values[{j}]"
                if not isinstance(v, dict):
                    bad(vat, "is not an object")
                for vk in v:
                    if vk not in VALUE_KEYS:
                        bad(f"{vat}.{vk}", "key outside schema 2")
                for vk in sorted(VALUE_KEYS):
                    if vk not in v:
                        bad(f"{vat}.{vk}", "missing")
                if not isinstance(v["name"], str) or not IDENT.match(v["name"]):
                    bad(f"{vat}.name", f"{v['name']!r} is not an identifier")
                if not is_int(v["value"]):
                    bad(f"{vat}.value", "is not an integer")
        elif k == K_ENUM:
            bad(f"{at}.values", "missing (an enum lists its values)")
        if qn in by:
            bad(at, "appears twice")
        by[qn] = t
    # Every name resolves inside the file.
    for i, t in enumerate(d["types"]):
        at = f"types[{i}] ({t['qualifiedName']})"
        if "inner" in t and t["inner"] not in by:
            bad(f"{at}.inner", f"{t['inner']!r} is not a type in this dump")
        for j, f in enumerate(t.get("fields", [])):
            if f["type"] not in by:
                bad(f"{at}.fields[{j}].type", f"{f['type']!r} is not a type in this dump")
    for lst in ("components", "events"):
        if not isinstance(d[lst], list):
            bad(lst, "is not a list")
        for j, q in enumerate(d[lst]):
            if q not in by:
                bad(f"{lst}[{j}]", f"{q!r} is not a type in this dump")
            if by[q]["kind"] != K_STRUCT:
                bad(f"{lst}[{j}]", f"{q} is kind {by[q]['kind']}, not a struct")
    d["_by"] = by
    d["_path"] = path
    return d


def pascal(ns):
    return "".join(p[:1].upper() + p[1:] for p in ns.split("_") if p)


class Model:
    """The generated C# for one schema-2 dump."""

    def __init__(self, dump, root):
        if not IDENT.match(root) or root in CS_KEYWORDS:
            raise GenError(f"--root {root!r} is not a C# identifier")
        self.d, self.by, self.root = dump, dump["_by"], root
        self.components, self.events = set(dump["components"]), set(dump["events"])
        self.names = {}       # qualifiedName -> C# name inside the root (structs, enums, bitmasks)
        self.flat = {}        # struct qualifiedName -> [(field, declaring qualifiedName)]
        self.layout_memo = {}
        self.raw_reasons = {}  # reason -> count of raw fields
        self.arrays = set()   # inline-array lengths in use
        self.wrappers = 0
        self.attributes = 0
        self.flattened = 0
        for q in sorted(self.components):
            t = self.by[q]
            if fnv1a32("keen::ecs::" + t["name"]) != int(t["hash"], 16):
                raise GenError(f"component {q}: kiln.world finds a component by the hash of keen::ecs::{t['name']}, "
                               f"which is not this type's hash {t['hash']}; typed access by name cannot reach it")
        self._name_all()
        for t in self.d["types"]:
            if t["kind"] == K_STRUCT:
                self._flatten(t)
        for t in sorted(self.d["types"], key=lambda t: 13 <= t["kind"] <= 16):  # enums before their bitmasks
            self._check_type(t)

    # --- names ------------------------------------------------------------------------------------------------------
    def short(self, qn):
        """keen::ecs::X and keen::X -> X; keen::<ns>::X -> <Ns>_X (deeper: every namespace part in PascalCase)."""
        parts = qn.split("::")
        name, ns = parts[-1], parts[:-1]
        if ns[:1] == ["keen"]:
            ns = ns[1:]
        if ns == ["ecs"]:
            ns = []
        if not IDENT.match(name):
            raise GenError(f"{qn}: its name {name!r} cannot be a C# type name")
        return "".join(pascal(p) for p in ns) + "_" + name if ns else name

    def _name_all(self):
        owner = {}

        def claim(cs, qn, what):
            if cs == self.root or cs in ROOT_RESERVED or re.match(r"^StaticArray\d+$", cs):
                raise GenError(f"{qn} ({what}) would be {self.root}.{cs}, a name the generator or the hand-written part "
                               f"of {self.root} uses")
            if cs in owner:
                raise GenError(f"name collision: {owner[cs]} and {qn} would both be {self.root}.{cs}")
            owner[cs] = f"{qn} ({what})"
            self.names[qn] = cs

        for t in self.d["types"]:
            if t["kind"] in (K_STRUCT, K_ENUM):
                claim(self.short(t["qualifiedName"]), t["qualifiedName"], "struct" if t["kind"] == K_STRUCT else "enum")
        for t in self.d["types"]:
            if 13 <= t["kind"] <= 16:
                e = self.by[t["inner"]]
                if e["kind"] != K_ENUM:
                    raise GenError(f"{t['qualifiedName']}: a bitmask's inner type must be an enum, {e['qualifiedName']} is "
                                   f"kind {e['kind']}")
                claim(self.short(e["qualifiedName"]) + "Mask", t["qualifiedName"], "bitmask")

    def cs_name(self, qn):
        return f"{self.root}.{self.names[qn]}"

    # --- structure checks -------------------------------------------------------------------------------------------
    def _flatten(self, t, seen=()):
        qn = t["qualifiedName"]
        if qn in self.flat:
            return self.flat[qn]
        if qn in seen:
            raise GenError(f"{qn}: its base chain loops")
        own = [(f, qn) for f in t["fields"]]
        base = []
        if "inner" in t:
            b = self.by[t["inner"]]
            if b["kind"] != K_STRUCT:
                raise GenError(f"{qn}: base {b['qualifiedName']} is kind {b['kind']}, not a struct")
            base = self._flatten(b, seen + (qn,))
            if base:  # an empty base takes no room (MSVC's empty-base optimisation); else own fields start after it
                for f, _ in own:
                    if f["offset"] < b["size"]:
                        raise GenError(f"{qn}.{f['name']} at {f['offset']} lies inside its base {b['qualifiedName']} "
                                       f"({b['size']} bytes)")
        names = {}
        allf = base + own
        for f, decl in allf:
            if f["name"] in names:
                raise GenError(f"{qn}: field {f['name']!r} is declared by {names[f['name']]} and by {decl}")
            names[f["name"]] = decl
        self.flat[qn] = allf
        return allf

    def _check_type(self, t):
        qn, k, size = t["qualifiedName"], t["kind"], t["size"]
        if k in PRIMS and PRIMS[k][1] != size:
            raise GenError(f"{qn}: kind {k} ({PRIMS[k][0]}) is {size} bytes, not {PRIMS[k][1]}")
        if k == K_ENUM:
            u = self.underlying(t)
            if u["kind"] not in INTEGER_KINDS or u["size"] != size:
                raise GenError(f"{qn}: an enum of {size} bytes over {u['qualifiedName']} (kind {u['kind']}, "
                               f"{u['size']} bytes) has no C# form")
            lo, hi = self._range(u["kind"], size)
            seen = set()
            for v in t["values"]:
                if not lo <= v["value"] <= hi:
                    raise GenError(f"{qn}.{v['name']} = {v['value']} does not fit {PRIMS[u['kind']][0]}")
                if v["name"] in seen or v["name"] == "value__":
                    raise GenError(f"{qn}: value name {v['name']!r} twice or reserved")
                seen.add(v["name"])
        if 13 <= k <= 16:
            cs, n = MASK_UNDERLYING[k]
            if size != n:
                raise GenError(f"{qn}: a kind-{k} bitmask is {n} bytes, this one {size}")
            e = self.by[t["inner"]]
            for v in e["values"]:
                if not 0 <= v["value"] < 8 * n:
                    raise GenError(f"{qn}: value {e['qualifiedName']}.{v['name']} = {v['value']} is not a bit of a "
                                   f"{8 * n}-bit mask")
            if "values" in t and t["values"] != e["values"]:
                raise GenError(f"{qn}: its own values differ from its enum's")
        if k == K_TYPEDEF:
            seen, x = {qn}, t
            while x["kind"] == K_TYPEDEF:
                x = self.by[x["inner"]]
                if x["qualifiedName"] in seen:
                    raise GenError(f"{qn}: its typedef chain loops")
                seen.add(x["qualifiedName"])
            if x["size"] != size:
                raise GenError(f"{qn}: typedef of {size} bytes over {x['qualifiedName']} of {x['size']}")
        if k == K_ARRAY:
            e = self.by[t["inner"]]
            if size % e["size"]:
                raise GenError(f"{qn}: {size} bytes is not a whole number of {e['qualifiedName']} ({e['size']} bytes)")
            m = re.search(r",(\d+)>$", qn)
            if m and int(m.group(1)) * e["size"] != size:
                raise GenError(f"{qn}: {size} bytes is not {m.group(1)} elements of {e['size']} bytes")
        if k == K_STRUCT:
            cs = self.names[qn]
            spans = []
            for f, decl in self.flat[qn]:
                n = f["name"]
                if n in STRUCT_MEMBERS:
                    raise GenError(f"{qn}.{n}: the field's name is one of the members every generated struct has "
                                   f"({', '.join(sorted(STRUCT_MEMBERS))})")
                if n == cs:
                    raise GenError(f"{qn}.{n}: a field cannot have its struct's C# name")
                if n in TABLE_METHODS:
                    raise GenError(f"{qn}.{n}: the field's name is a generated method's name in the layout table "
                                   f"({', '.join(sorted(TABLE_METHODS))})")
                fs = self.by[f["type"]]["size"]
                if f["offset"] + fs > size:
                    raise GenError(f"{qn}.{n}: {f['offset']} + {fs} ends past the struct's {size} bytes")
                spans.append((f["offset"], f["offset"] + fs, n))
            spans.sort()
            for a, b in zip(spans, spans[1:]):
                if b[0] < a[1]:
                    raise GenError(f"{qn}: fields {a[2]} and {b[2]} overlap")

    def underlying(self, enum):
        """An enum's integer type, through typedefs."""
        u, seen = self.by[enum["inner"]], set()
        while u["kind"] == K_TYPEDEF and u["qualifiedName"] not in seen:
            seen.add(u["qualifiedName"])
            u = self.by[u["inner"]]
        return u

    @staticmethod
    def _range(kind, size):
        bits = 8 * size
        return (-(1 << (bits - 1)), (1 << (bits - 1)) - 1) if kind in SIGNED_KINDS else (0, (1 << bits) - 1)

    # --- types of fields --------------------------------------------------------------------------------------------
    def field_type(self, qn):
        """(C# type, None) for a type the generator can express, or (None, reason) for a raw byte buffer."""
        t = self.by[qn]
        k = t["kind"]
        if k in PRIMS:
            return PRIMS[k][0], None
        if k in (K_ENUM, K_STRUCT) or 13 <= k <= 16:
            return self.cs_name(qn), None
        if k == K_TYPEDEF:
            return self.field_type(t["inner"])
        if k == K_ARRAY:
            e = self.by[t["inner"]]
            et, why = self.field_type(e["qualifiedName"])
            if et is None:
                return None, f"an array of {why}"
            n = t["size"] // e["size"]
            self.arrays.add(n)
            return f"{self.root}.StaticArray{n}<{et}>", None
        if k in (K_REF, K_GUID):
            if t["size"] != 16:
                return None, f"a kind-{k} leaf of {t['size']} bytes (expected 16)"
            return f"{self.root}.{'ObjectReference' if k == K_REF else 'GameGuid'}", None
        return None, LEAF_NAMES.get(k, f"a kind-{k} leaf (blob or ds data the generator does not read)")

    # --- layout hash ------------------------------------------------------------------------------------------------
    def layout_text(self, qn):
        t = self.by[qn]
        k = t["kind"]
        if k in PRIMS:
            return f"primitive {qn}\nkind {k}\nsize {t['size']}\n"
        if k == K_ENUM:
            return (f"enum {qn}\nsize {t['size']}\nunderlying {t['inner']}\n"
                    + "".join(f"value {v['name']}={v['value']}\n" for v in t["values"]))
        if 13 <= k <= 16:
            return f"bitmask {qn}\nsize {t['size']}\nenum {t['inner']} {self.layout(t['inner']):016x}\n"
        if k == K_TYPEDEF:
            return f"typedef {qn}\ntarget {t['inner']} {self.layout(t['inner']):016x}\n"
        if k == K_ARRAY:
            e = self.by[t["inner"]]
            return f"array {qn}\nlength {t['size'] // e['size']}\nelement {t['inner']} {self.layout(t['inner']):016x}\n"
        if k == K_STRUCT:
            s = f"struct {qn}\nsize {t['size']}\nalign {t['align']}\n"
            s += f"base {t['inner']} {self.layout(t['inner']):016x}\n" if "inner" in t else "base -\n"
            for f in t["fields"]:
                s += f"field {f['name']} {f['offset']} {f['type']} {self.layout(f['type']):016x}\n"
            return s
        return f"leaf {qn}\nkind {k}\nsize {t['size']}\nalign {t['align']}\n"

    def layout(self, qn):
        if qn not in self.layout_memo:
            self.layout_memo[qn] = fnv1a64(self.layout_text(qn))
        return self.layout_memo[qn]

    # --- emission ---------------------------------------------------------------------------------------------------
    def role(self, qn):
        return "component" if qn in self.components else "event" if qn in self.events else "struct"

    def emit(self):
        r = self.root
        body, table = [], []
        order = sorted((t for t in self.d["types"] if t["qualifiedName"] in self.names),
                       key=lambda t: self.names[t["qualifiedName"]])
        for t in order:
            k = t["kind"]
            if k == K_STRUCT:
                body.append(self._emit_struct(t, table))
            elif k == K_ENUM:
                body.append(self._emit_enum(t, table))
            else:
                body.append(self._emit_mask(t, table))
        arrays = []
        for n in sorted(self.arrays):
            arrays.append(
                f"    /// <summary>A game <c>StaticArray</c> of {n} elements: {n} × the element's size, no padding.</summary>\n"
                f"    [InlineArray({n})]\n"
                f"    public struct StaticArray{n}<T>\n"
                f"    {{\n"
                f"        private T _element0;\n"
                f"    }}\n")
        head = (f"{MARKER}\n"
                f"// SPDX-License-Identifier: MIT\n"
                f"// <auto-generated> by tools/typegen/typegen.py from {os.path.basename(self.d['_path'])} "
                f"(side: {self.d['side']}). Do not edit by hand.\n"
                f"#nullable enable\n"
                f"#pragma warning disable RS0016 // generated game types follow the game: outside the public API record\n"
                f"#pragma warning disable CS0169 // an inline array's element field is used through the array\n"
                f"using System.Runtime.CompilerServices;\n"
                f"using System.Runtime.InteropServices;\n"
                f"\n"
                f"namespace Kiln;\n"
                f"\n"
                f"public static partial class {r}\n"
                f"{{\n")
        types_cs = head + "\n".join(body) + "}\n"
        arrays_cs = head + "\n".join(arrays) + "}\n"
        table.sort(key=lambda line: line.split("\t", 2)[1])
        tbody = "".join(line + "\n" for line in table)
        header = (f"kiln.game.layouts\t1\tside={self.d['side']}\texe_sha256={self.d['exe_sha256']}\troot={r}"
                  f"\ttypes={len(table)}\tset={fnv1a64(tbody):016x}\n")
        return types_cs, arrays_cs, MARKER + "\n" + header + tbody, self.types_text()

    def types_text(self):
        """Kiln.Game.types: every type of the dump, for the first-use check against the live type table (§4)."""
        lines = []
        for t in sorted(self.d["types"], key=lambda t: t["qualifiedName"]):
            parts = [t["qualifiedName"], str(t["kind"]), str(t["size"]), t["hash"], t.get("inner", "-")]
            if t["kind"] == K_STRUCT:
                parts += [f"{f['name']}@{f['offset']}:{f['type']}" for f in t["fields"]]
            elif t["kind"] == K_ENUM:
                parts += [f"{v['name']}={v['value']}" for v in t["values"]]
            lines.append("\t".join(parts) + "\n")
        return (f"{MARKER}\nkiln.game.types\t1\tside={self.d['side']}\texe_sha256={self.d['exe_sha256']}"
                f"\ttypes={len(lines)}\n" + "".join(lines))

    def attribute_value(self, t):
        """The C# element type of an attribute component's dataStorage (a component whose base chain runs through
        keen::ecs::AttributeComponent and that has a dataStorage static array), else None."""
        qn = t["qualifiedName"]
        if qn not in self.components:
            return None
        x, chain = t, set()
        while "inner" in x:
            x = self.by[x["inner"]]
            chain.add(x["qualifiedName"])
        if "keen::ecs::AttributeComponent" not in chain:
            return None
        for f, _ in self.flat[qn]:
            if f["name"] != "dataStorage":
                continue
            a = self.by[f["type"]]
            while a["kind"] == K_TYPEDEF:
                a = self.by[a["inner"]]
            if a["kind"] != K_ARRAY:
                return None
            et, why = self.field_type(a["inner"])
            return et
        return None

    def _emit_struct(self, t, table):
        qn, r = t["qualifiedName"], self.root
        cs = self.names[qn]
        role = self.role(qn)
        iface = {"component": "IGameComponent", "event": "IGameEvent"}.get(role, "IGameStruct")
        value = self.attribute_value(t)
        ifaces = f"IGameAttribute<{cs}, {value}>" if value else f"{iface}<{cs}>"
        fields, members, unsafe = [], [], False
        for f, decl in self.flat[qn]:
            if decl != qn:
                self.flattened += 1
            ft, why = self.field_type(f["type"])
            ftype = self.by[f["type"]]
            note = f["type"]
            x = ftype
            while x["kind"] == K_TYPEDEF:
                x = self.by[x["inner"]]
                note += f" = {x['qualifiedName']}"
            if decl != qn:
                note += f", from {decl}"
            n = cs_id(f["name"])
            if ft is None:
                unsafe = True
                self.raw_reasons[why] = self.raw_reasons.get(why, 0) + 1
                fields.append(f"        /// <summary><c>{f['name']}</c>: <c>{esc(note)}</c>. Raw bytes: {why}.</summary>\n"
                              f"        [FieldOffset({f['offset']})] public fixed byte {n}[{ftype['size']}];\n")
                members.append(f"{f['name']}@{f['offset']}:fixed byte[{ftype['size']}]")
            else:
                fields.append(f"        /// <summary><c>{f['name']}</c>: <c>{esc(note)}</c>.</summary>\n"
                              f"        [FieldOffset({f['offset']})] public {ft} {n};\n")
                members.append(f"{f['name']}@{f['offset']}:{ft}")
        flat = self.flat[qn]
        wrapper = ""
        if len(flat) == 1 and flat[0][0]["offset"] == 0 and self.by[flat[0][0]["type"]]["size"] == t["size"]:
            ft, why = self.field_type(flat[0][0]["type"])
            if ft is not None:
                self.wrappers += 1
                n = cs_id(flat[0][0]["name"])
                # the stamps see a mod's use of the conversions as this member (docs/kiln/typegen.md §3.6)
                members.append(f"op_Implicit@method:{ft}")
                wrapper = (f"        /// <summary>The wrapped value.</summary>\n"
                           f"        public static implicit operator {ft}({cs} value) => value.{n};\n"
                           f"        /// <summary>Wraps a value.</summary>\n"
                           f"        public static implicit operator {cs}({ft} value) => new() {{ {n} = value }};\n")
        attr = ""
        if value:
            self.attributes += 1
            members.append(f"get_Values@method:Span<{value}>")
            attr = (f"        /// <summary>The attribute's value slots (<c>dataStorage</c>). Which slot is the current, the base or the "
                    f"maximum value is the game's data, not named here.</summary>\n"
                    f"        [global::System.Diagnostics.CodeAnalysis.UnscopedRef]\n"
                    f"        public Span<{value}> Values => dataStorage;\n"
                    f"        static Span<{value}> IGameAttribute<{cs}, {value}>.ValuesOf(ref {cs} self) => self.dataStorage;\n")
        lay = self.layout(qn)
        base = f" Base <c>{esc(t['inner'])}</c>." if "inner" in t else ""
        what = {"component": "an ECS component", "event": "an ECS event", "struct": "a game struct"}[role]
        table.append("\t".join([f"S", f"Kiln.{r}+{cs}", f"{lay:016x}", qn, str(t["size"]), role] + members))
        return (f"    /// <summary><c>{esc(qn)}</c>: {what}, {t['size']} bytes, align {t['align']}.{base}</summary>\n"
                f"    [StructLayout(LayoutKind.Explicit, Size = {t['size']})]\n"
                f"    public {'unsafe ' if unsafe else ''}partial struct {cs} : {ifaces}\n"
                f"    {{\n"
                f"        /// <summary>The engine's type hash: FNV-1a-32 of <see cref=\"QualifiedName\"/>.</summary>\n"
                f"        public static readonly uint Hash = 0x{int(t['hash'], 16):08X}u;\n"
                f"        /// <summary>The game's short name, the one kiln.world uses.</summary>\n"
                f"        public static readonly string Name = \"{t['name']}\";\n"
                f"        /// <summary>The game's qualified name.</summary>\n"
                f"        public static readonly string QualifiedName = \"{qn}\";\n"
                f"        /// <summary>The size in bytes.</summary>\n"
                f"        public static readonly int Size = {t['size']};\n"
                f"        /// <summary>The layout hash (docs/kiln/typegen.md §3).</summary>\n"
                f"        public static readonly ulong Layout = 0x{lay:016X}ul;\n"
                f"        static uint IGameStruct<{cs}>.Hash => Hash;\n"
                f"        static string IGameStruct<{cs}>.Name => Name;\n"
                f"        static string IGameStruct<{cs}>.QualifiedName => QualifiedName;\n"
                f"        static int IGameStruct<{cs}>.Size => Size;\n"
                f"        static ulong IGameStruct<{cs}>.Layout => Layout;\n"
                + "".join(fields) + wrapper + attr +
                f"    }}\n")

    def _emit_enum(self, t, table):
        qn, r = t["qualifiedName"], self.root
        cs = self.names[qn]
        u = self.underlying(t)
        under = PRIMS[u["kind"]][0]
        lay = self.layout(qn)
        table.append("\t".join(["E", f"Kiln.{r}+{cs}", f"{lay:016x}", qn, str(t["size"]), under]
                               + [f"{v['name']}={v['value']}" for v in t["values"]]))
        vals = "".join(f"        {cs_id(v['name'])} = {v['value']},\n" for v in t["values"])
        return (f"    /// <summary>Game enum <c>{esc(qn)}</c>: {t['size']} byte(s) over <c>{u['qualifiedName']}</c>. "
                f"Layout 0x{lay:016X}.</summary>\n"
                f"    public enum {cs} : {under}\n"
                f"    {{\n{vals}    }}\n")

    def _emit_mask(self, t, table):
        qn, r = t["qualifiedName"], self.root
        cs = self.names[qn]
        e = self.by[t["inner"]]
        under, n = MASK_UNDERLYING[t["kind"]]
        one = {"byte": "1", "ushort": "1", "uint": "1u", "ulong": "1ul"}[under]
        lay = self.layout(qn)
        table.append("\t".join(["F", f"Kiln.{r}+{cs}", f"{lay:016x}", qn, str(t["size"]), under]
                               + [f"{v['name']}={1 << v['value']}" for v in e["values"]]))
        vals = "".join(f"        {cs_id(v['name'])} = {one} << {v['value']},\n" for v in e["values"])
        return (f"    /// <summary>Game bitmask <c>{esc(qn)}</c>: {n} byte(s); bit <c>n</c> stands for the value <c>n</c> of "
                f"<see cref=\"{cs[:-4]}\"/>. Layout 0x{lay:016X}.</summary>\n"
                f"    [System.Flags]\n"
                f"    public enum {cs} : {under}\n"
                f"    {{\n{vals}    }}\n")

    def summary(self):
        from collections import Counter
        kinds = Counter(t["kind"] for t in self.d["types"])
        nfields = sum(len(self.flat[q]) for q in self.flat)
        raw = sum(self.raw_reasons.values())
        reasons = "; ".join(f"{c} {w}" for w, c in sorted(self.raw_reasons.items(), key=lambda x: (-x[1], x[0])))
        return (f"typegen: {os.path.basename(self.d['_path'])} ({self.d['side']}): {len(self.d['types'])} types: "
                f"{kinds[K_STRUCT]} structs, {kinds[K_ENUM]} enums, {sum(kinds[k] for k in range(13, 17))} bitmasks, "
                f"{kinds[K_TYPEDEF]} typedefs, {kinds[K_ARRAY]} static arrays, {sum(kinds[k] for k in PRIMS)} primitives, "
                f"{sum(c for k, c in kinds.items() if k >= 20)} leaves; {len(self.components)} components, "
                f"{len(self.events)} events; {nfields} fields ({self.flattened} from bases), {self.wrappers} wrappers, "
                f"{self.attributes} attribute views, "
                f"{len(self.arrays)} inline-array lengths; {raw} raw buffers" + (f" ({reasons})" if raw else ""))


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def legacy_from_v2(m, obsolete):
    """The nine dev.24 types, from a schema-2 dump, in the shape the v1 emitter reads (their own fields only)."""
    types = []
    for name in LEGACY:
        qn = f"keen::ecs::{name}"
        t = m.by.get(qn)
        if t is None or t["kind"] != K_STRUCT:
            raise GenError(f"the dev.24 type {qn} is not a struct in this dump: the legacy part (namespace "
                           f"Kiln.GameTypes) cannot be made; build with -p:KilnLocalGameTypes=<file> or --no-legacy")
        fields = [{"name": f["name"], "offset": f["offset"], "type": f["type"], "size": m.by[f["type"]]["size"],
                   "kind": m.by[f["type"]]["kind"]} for f in t["fields"]]
        types.append({"name": name, "qualifiedName": qn, "hash": t["hash"], "size": t["size"], "kind": K_STRUCT,
                      "fields": fields})
    of = (lambda t: f"Use Kiln.{m.root}.{m.names[t['qualifiedName']]}.") if obsolete else None
    return legacy_text(types, m.d["_path"], m.d["side"], of, header=[MARKER])


OUTPUTS = ("Kiln.Game.Ecs.g.cs", "Kiln.Game.Arrays.g.cs", "Kiln.Game.Legacy.g.cs", "Kiln.Game.layouts",
           "Kiln.Game.types")


def generate(argv):
    import argparse
    ap = argparse.ArgumentParser(prog="typegen.py generate", description="Generate Kiln.Game from a schema-2 dump.")
    ap.add_argument("--dump", required=True, help="a schema-2 dump (sigdb/types/<side>/<sha>.json)")
    ap.add_argument("--out", required=True, help="the directory to write into")
    ap.add_argument("--root", default="Ecs", help="the static class in namespace Kiln holding the types (default Ecs)")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--legacy-obsolete", action="store_true", help="mark the nine dev.24 types [Obsolete]")
    g.add_argument("--no-legacy", action="store_true", help="write no legacy part (it comes from elsewhere)")
    a = ap.parse_args(argv)
    try:
        m = Model(load_dump(a.dump), a.root)
        types_cs, arrays_cs, table, types = m.emit()
        legacy = "" if a.no_legacy else legacy_from_v2(m, a.legacy_obsolete)
    except GenError as e:
        print(f"typegen: error: {e}", file=sys.stderr)
        return 1
    os.makedirs(a.out, exist_ok=True)
    texts = (types_cs, arrays_cs, legacy if not a.no_legacy else MARKER + "\n// no legacy part (--no-legacy)\n", table,
             types)
    for name, text in zip(OUTPUTS, texts):
        with open(os.path.join(a.out, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print(m.summary())
    return 0



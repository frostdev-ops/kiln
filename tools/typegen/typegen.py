"""Generate Kiln.Game bindings from a reflection type dump.

Reads a dump produced by the lab probe (tools/typegen/probe, which walks the game's reflection registry through
content/TypeByHash via kiln.hooks) and emits explicit-layout C# structs, component type-hash constants and a
Type->name map for the typed read API. The structs mirror the engine's exact field offsets and sizes, so
World.TryRead<NetworkHealth> and Kiln.Game's Components.Get<T> read real component memory.

    python3 tools/typegen/typegen.py sigdb/types/server/<sha>.json managed/Kiln.Game/Generated.cs
"""
import json
import sys

# reflection kind -> blittable C# primitive (fixed width). Other kinds become a raw byte buffer of the field size.
PRIM = {1: "byte", 2: "byte", 3: "sbyte", 4: "ushort", 5: "short", 6: "uint", 7: "int",
        8: "ulong", 9: "long", 0xA: "float", 0xB: "double"}
BY_SIZE = {1: "byte", 2: "ushort", 4: "uint", 8: "ulong"}


def cs_type(field):
    """Return (csharp_type, is_fixed_buffer) for a field, or (None, True) for a raw byte buffer."""
    kind, size, t = field["kind"], field["size"], field["type"]
    if kind in PRIM:
        return PRIM[kind], False
    if kind == 0xC:  # enum: use the underlying integer of its size
        return BY_SIZE.get(size, None), size not in BY_SIZE
    if kind == 0x11:  # typedef (e.g. keen::float -> float32)
        if "float" in t:
            return ("double" if size == 8 else "float"), False
        return BY_SIZE.get(size, None), size not in BY_SIZE
    return None, True  # struct / array / guid / blob: exact-size raw bytes


def ident(name):
    kw = {"object", "string", "event", "params", "lock", "base", "class", "default", "fixed", "ref", "out"}
    return "@" + name if name in kw else name


def gen_struct(t):
    lines = []
    name, size = t["name"], t["size"]
    lines.append(f"/// <summary>ECS component <c>{t['qualifiedName']}</c> ({size} bytes). Generated; exact engine layout.</summary>")
    lines.append(f"[StructLayout(LayoutKind.Explicit, Size = {size})]")
    lines.append(f"public unsafe struct {name}")
    lines.append("{")
    lines.append(f"    /// <summary>The engine type hash (FNV-1a-32 of the qualified name).</summary>")
    lines.append(f"    public const uint Hash = {t['hash']};")
    lines.append(f'    /// <summary>The ECS component name used by kiln.world.</summary>')
    lines.append(f'    public const string Component = "{name}";')
    for f in t["fields"]:
        if not f["name"]:
            continue
        cst, is_buf = cs_type(f)
        off, fn = f["offset"], ident(f["name"])
        comment = f"  // {f['type']}"
        if is_buf or cst is None:
            lines.append(f"    [FieldOffset({off})] public fixed byte {fn}[{max(1, f['size'])}];{comment} (raw)")
        else:
            lines.append(f"    [FieldOffset({off})] public {cst} {fn};{comment}")
    lines.append("}")
    return "\n".join(lines)


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(2)
    dump = json.load(open(sys.argv[1]))
    types = dump["types"]
    out = []
    out.append("// SPDX-License-Identifier: MIT")
    out.append("// <auto-generated> by tools/typegen/typegen.py from a reflection dump. Do not edit by hand.")
    out.append(f"// Source: {sys.argv[1]} (side: {dump.get('side', '?')}, {len(types)} types).")
    out.append("using System.Runtime.InteropServices;")
    out.append("")
    out.append("namespace Kiln.GameTypes;")
    out.append("")
    for t in types:
        out.append(gen_struct(t))
        out.append("")
    # type-hash constants
    out.append("/// <summary>Type-hash constants for every generated ECS component.</summary>")
    out.append("public static class ComponentTypes")
    out.append("{")
    for t in types:
        out.append(f"    public const uint {t['name']} = {t['hash']};")
    out.append("}")
    out.append("")
    # Type -> component-name map for the typed read API.
    out.append("internal static class ComponentRegistry")
    out.append("{")
    out.append("    public static readonly System.Collections.Generic.Dictionary<System.Type, string> Names = new()")
    out.append("    {")
    for t in types:
        out.append(f'        [typeof({t["name"]})] = "{t["name"]}",')
    out.append("    };")
    out.append("}")
    out.append("")
    open(sys.argv[2], "w").write("\n".join(out))
    print(f"typegen: wrote {len(types)} struct(s) to {sys.argv[2]}")


if __name__ == "__main__":
    main()

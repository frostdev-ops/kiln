// Build script: Tauri's codegen, the git commit for app_info, and the schema fixtures the
// `--selftest` mode embeds (resolver parity cases and Steam VDF samples from ../../schema/fixtures).
use std::fmt::Write as _;
use std::path::Path;

fn main() {
    let repo = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    // KILN_GIT names the commit when there is no .git (a release builds from a `git archive` export)
    let commit = std::env::var("KILN_GIT").ok().filter(|c| !c.trim().is_empty()).unwrap_or_else(|| {
        std::process::Command::new("git")
            .args(["-C", &repo.display().to_string(), "rev-parse", "--short=7", "HEAD"])
            .output()
            .ok()
            .filter(|o| o.status.success())
            .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
            .unwrap_or_default()
    });
    println!("cargo:rustc-env=KILN_GIT_COMMIT={commit}");
    println!("cargo:rerun-if-env-changed=KILN_GIT");
    println!("cargo:rerun-if-changed=../../.git/HEAD");

    let mut out = String::from("// generated by build.rs\n");
    for (name, dir) in [("RESOLVER_FIXTURES", "schema/fixtures/resolver"), ("VDF_FIXTURES", "schema/fixtures/vdf")] {
        let d = repo.join(dir);
        println!("cargo:rerun-if-changed={}", d.display());
        let mut files: Vec<_> = std::fs::read_dir(&d).map(|r| r.flatten().map(|e| e.path()).collect()).unwrap_or_default();
        files.sort();
        writeln!(out, "pub const {name}: &[(&str, &str)] = &[").unwrap();
        for f in files.iter().filter(|f| f.is_file()) {
            let abs = std::fs::canonicalize(f).unwrap();
            writeln!(out, "    ({:?}, include_str!({:?})),", f.file_name().unwrap().to_string_lossy(), abs.display().to_string()).unwrap();
        }
        writeln!(out, "];").unwrap();
    }
    std::fs::write(Path::new(&std::env::var("OUT_DIR").unwrap()).join("fixtures.rs"), out).unwrap();

    tauri_build::build()
}

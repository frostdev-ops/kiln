// Build script: Tauri's codegen, the git commit for app_info, and the schema fixtures the
// `--selftest` mode embeds (resolver parity cases and Steam VDF samples from ../../schema/fixtures).
use std::fmt::Write as _;
use std::path::Path;
#[path = "../../crates/kiln-manage/src/nexus/oauth/registration.rs"]
mod oauth_registration;

fn main() {
    for name in ["KILN_NEXUS_ENABLED", "KILN_RELEASE_BUILD", "KILN_NEXUS_OAUTH_CLIENT_ID", "KILN_NEXUS_OAUTH_REDIRECT_URI"] {
        println!("cargo:rerun-if-env-changed={name}");
    }
    println!("cargo:rerun-if-changed=../../crates/kiln-manage/src/nexus/oauth/registration.rs");
    let client_id = std::env::var("KILN_NEXUS_OAUTH_CLIENT_ID").ok();
    let redirect_uri = std::env::var("KILN_NEXUS_OAUTH_REDIRECT_URI").ok();
    oauth_registration::preflight(std::env::var_os("KILN_RELEASE_BUILD").is_some(), std::env::var("KILN_NEXUS_ENABLED").ok().as_deref(), client_id.as_deref(), redirect_uri.as_deref())
        .unwrap_or_else(|reason| panic!("Nexus OAuth release preflight: {reason}"));
    // Plain `cargo build --no-default-features` must be safe too; do not rely on the packaging wrapper to remove
    // the updater key. Both tauri-build and generate_context! read this same final RFC 7396 merge patch.
    println!("cargo:rerun-if-changed=tauri.nexus.conf.json");
    let mut config: serde_json::Value = std::env::var("TAURI_CONFIG")
        .map(|s| serde_json::from_str(&s).expect("TAURI_CONFIG must be JSON"))
        .unwrap_or_else(|_| serde_json::json!({}));
    if std::env::var_os("CARGO_FEATURE_SELF_UPDATE").is_none() {
        config["plugins"]["updater"] = serde_json::Value::Null;
        config["bundle"]["createUpdaterArtifacts"] = false.into();
        let patch = serde_json::to_string(&config).unwrap();
        // This build script is single threaded; no threads or subprocesses have been started yet.
        unsafe { std::env::set_var("TAURI_CONFIG", &patch); }
        println!("cargo:rustc-env=TAURI_CONFIG={patch}");
    } else if config.get("plugins").and_then(|p| p.get("updater")).is_some_and(|v| v.is_null()) {
        panic!("The Nexus Tauri config requires --no-default-features and no self-update feature");
    }
    let repo = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    // KILN_GIT names the commit when there is no .git (a release builds from a `git archive` export)
    let commit = std::env::var("KILN_GIT").ok().filter(|c| !c.trim().is_empty()).unwrap_or_else(|| {
        std::process::Command::new("git")
            .args(["-C", &repo.display().to_string(), "rev-parse", "--short=7", "HEAD"])
            .output()
            .ok()
            .filter(|o| o.status.success())
            .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
            .unwrap_or_default()
    });
    println!("cargo:rustc-env=KILN_GIT_COMMIT={commit}");
    println!("cargo:rerun-if-env-changed=KILN_GIT");
    println!("cargo:rerun-if-changed=../../.git/HEAD");

    let mut out = String::from("// generated by build.rs\n");
    for (name, dir) in [("RESOLVER_FIXTURES", "schema/fixtures/resolver"), ("VDF_FIXTURES", "schema/fixtures/vdf")] {
        let d = repo.join(dir);
        println!("cargo:rerun-if-changed={}", d.display());
        let mut files: Vec<_> = std::fs::read_dir(&d).map(|r| r.flatten().map(|e| e.path()).collect()).unwrap_or_default();
        files.sort();
        writeln!(out, "pub const {name}: &[(&str, &str)] = &[").unwrap();
        for f in files.iter().filter(|f| f.is_file()) {
            let abs = std::fs::canonicalize(f).unwrap();
            writeln!(out, "    ({:?}, include_str!({:?})),", f.file_name().unwrap().to_string_lossy(), abs.display().to_string()).unwrap();
        }
        writeln!(out, "];").unwrap();
    }
    std::fs::write(Path::new(&std::env::var("OUT_DIR").unwrap()).join("fixtures.rs"), out).unwrap();

    tauri_build::build()
}

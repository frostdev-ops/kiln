// Generates src/theme/tokens.css from branding/palette.json (the palette is the brand's).
//   bun run tokens
// Every palette key becomes --k-<name>; rules become --k-text-on-ember / --k-ember-text-on-light.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

type Palette = {
  name: string;
  version: number;
  colors: Record<string, string>;
  gradients: Record<string, { angle: number; stops: [string, number][] }>;
  effects: Record<string, string>;
  radii: Record<string, number>;
  fonts: Record<string, string>;
  rules: Record<string, string>;
};

const root = join(import.meta.dir, "..");
const palette: Palette = JSON.parse(readFileSync(join(root, "..", "branding", "palette.json"), "utf8"));
const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());
const fallbacks: Record<string, string> = {
  display: 'Georgia, "Times New Roman", serif',
  ui: 'system-ui, -apple-system, "Segoe UI", Roboto, sans-serif',
  mono: 'ui-monospace, "Cascadia Mono", Consolas, "DejaVu Sans Mono", monospace',
};

const lines: string[] = [];
lines.push(`/* Generated by scripts/gen-tokens.ts from branding/palette.json ("${palette.name}" v${palette.version}). Do not edit. */`);
lines.push("/* Fonts are bundled locally by the launcher (OFL): no web-font URLs. Text on ember/gold fills is --k-text-on-ember. */");
lines.push(":root {");
for (const [k, v] of Object.entries(palette.colors)) lines.push(`  --k-${k}: ${v};`);
for (const [k, g] of Object.entries(palette.gradients))
  lines.push(`  --k-grad-${k}: linear-gradient(${g.angle}deg, ${g.stops.map(([c, at]) => `${c} ${at * 100}%`).join(", ")});`);
for (const [k, v] of Object.entries(palette.effects)) lines.push(`  --k-${k}: ${v};`);
for (const [k, v] of Object.entries(palette.radii)) lines.push(`  --k-radius-${k}: ${v}px;`);
for (const [k, v] of Object.entries(palette.fonts)) lines.push(`  --k-font-${k}: "${v}", ${fallbacks[k] ?? "sans-serif"};`);
for (const [k, v] of Object.entries(palette.rules)) lines.push(`  --k-${kebab(k)}: ${v};`);
lines.push("}");
writeFileSync(join(root, "src", "theme", "tokens.css"), lines.join("\n") + "\n");
console.log(`tokens.css: ${lines.length - 4} tokens`);
